/// Whether a key's `KeyCode` variant name is a modifier (`ShiftLeft`, `ControlRight`, `AltLeft`,
/// `SuperLeft`, `MetaRight`, `HyperLeft`, or the bare `Meta`), the keys a chord holds and never one
/// it is.
///
/// ```
/// assert!(bevy_gooey::model::is_modifier_key("ControlLeft"));
/// assert!(!bevy_gooey::model::is_modifier_key("KeyK"));
/// ```
pub fn is_modifier_key(code: &str) -> bool {
    ["Shift", "Control", "Alt", "Super", "Meta", "Hyper"]
        .iter()
        .any(|name| {
            code.strip_prefix(name)
                .is_some_and(|side| matches!(side, "" | "Left" | "Right"))
        })
}

/// How a chord spells its modifiers and named keys: Apple's symbols, or words that every font can
/// draw.
///
/// A mac spells a chord with symbols (`⌃⌥⇧⌘`, and `↩⌫⌦⎋⇥` for a few keys), which is the platform's
/// own notation — but symbols are only glyphs, and a face that does not map a codepoint draws a
/// tofu box. A host that ships a monospace coding face, as a tool normally does, gets a box on
/// nearly every Command chord: Bevy's own bundled default font (FiraMono's 95-codepoint subset)
/// maps **none** of the thirteen a mac chord can wear, and the issue that asked for this
/// ([#45](https://github.com/bevy-coven/bevy_gooey/issues/45)) measured a host's face missing seven
/// of them. [`ChordGlyphs::Words`] spells the same chords in ASCII — `Cmd+Z`, `Shift+Cmd+P`,
/// `Ctrl+Esc` — so the player can always read the interface.
///
/// It is a host setting, [`crate::BindingSettings::chord_glyphs`], because only the host knows
/// which face it shipped. `Glyphs` is the default: the notation is Apple's and a face that carries
/// the symbols loses nothing. On a platform that is not a mac the two are the same string —
/// Microsoft's notation is already words.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
pub enum ChordGlyphs {
    /// Apple's symbols on a mac: "⇧⌘P", "⌥↩", "⌃⎋".
    #[default]
    Glyphs,
    /// Words in ASCII, on every platform: "Shift+Cmd+P", "Opt+Enter", "Ctrl+Esc". Apple's order
    /// and its names, `Ctrl` `Opt` `Shift` `Cmd`; the key is named by [`key_name`], as a prompt
    /// names it.
    Words,
}

impl ChordGlyphs {
    /// Every spelling, in the order a settings row offers them.
    pub const ALL: [Self; 2] = [Self::Glyphs, Self::Words];

    /// The spelling's name in a settings row: "Glyphs", "Words".
    pub fn name(self) -> &'static str {
        match self {
            Self::Glyphs => "Glyphs",
            Self::Words => "Words",
        }
    }
}

/// The words of a key chord as the platform spells them, from a `KeyCode` variant name and the
/// modifiers held, `[ctrl, shift, alt, meta]`.
///
/// Apple's order is Control, Option, Shift, Command, as symbols with nothing between ("⇧⌘P"),
/// and a few keys wear glyphs (Return, Delete, Escape, Tab, the arrows). Elsewhere it is
/// Microsoft's order: Windows logo (named "Super"), Ctrl, Alt, Shift, joined by "+"
/// ("Ctrl+Shift+P"). `meta` is the Command key on a mac and the Windows or Super key elsewhere.
///
/// [`ChordGlyphs::Words`] is the same order in ASCII, for a host whose face has no symbols
/// ("Shift+Cmd+P", "Opt+Enter"); on anything but a mac it changes nothing.
///
/// ```
/// use bevy_gooey::model::{ChordGlyphs, shortcut_label};
/// assert_eq!(shortcut_label("KeyP", [true, true, false, false], false, ChordGlyphs::Glyphs), "Ctrl+Shift+P");
/// assert_eq!(shortcut_label("KeyP", [false, true, false, true], true, ChordGlyphs::Glyphs), "⇧⌘P");
/// assert_eq!(shortcut_label("KeyP", [false, true, false, true], true, ChordGlyphs::Words), "Shift+Cmd+P");
/// ```
pub fn shortcut_label(
    code: &str,
    [ctrl, shift, alt, meta]: [bool; 4],
    mac: bool,
    glyphs: ChordGlyphs,
) -> String {
    if mac {
        // Apple's order, as symbols with nothing between, or as words joined by "+".
        let mut out = String::new();
        let names = [
            (ctrl, "Ctrl", '⌃'),
            (alt, "Opt", '⌥'),
            (shift, "Shift", '⇧'),
            (meta, "Cmd", '⌘'),
        ];
        for (held, name, glyph) in names {
            if !held {
                continue;
            }
            match glyphs {
                ChordGlyphs::Glyphs => out.push(glyph),
                ChordGlyphs::Words => {
                    out.push_str(name);
                    out.push('+');
                }
            }
        }
        // A key wears its own glyph, or `key_name`'s words — "Esc", as a prompt names it.
        out.push_str(&match (glyphs, code) {
            (ChordGlyphs::Glyphs, "Enter") => "↩".to_owned(),
            (ChordGlyphs::Glyphs, "Backspace") => "⌫".to_owned(),
            (ChordGlyphs::Glyphs, "Delete") => "⌦".to_owned(),
            (ChordGlyphs::Glyphs, "Escape") => "⎋".to_owned(),
            (ChordGlyphs::Glyphs, "Tab") => "⇥".to_owned(),
            (ChordGlyphs::Glyphs, "ArrowUp") => "↑".to_owned(),
            (ChordGlyphs::Glyphs, "ArrowDown") => "↓".to_owned(),
            (ChordGlyphs::Glyphs, "ArrowLeft") => "←".to_owned(),
            (ChordGlyphs::Glyphs, "ArrowRight") => "→".to_owned(),
            _ => key_name(code),
        });
        return out;
    }
    let mut out = String::new();
    for (held, name) in [
        (meta, "Super"),
        (ctrl, "Ctrl"),
        (alt, "Alt"),
        (shift, "Shift"),
    ] {
        if held {
            out.push_str(name);
            out.push('+');
        }
    }
    out + &key_name(code)
}

/// Every pair of commands bound to the same shortcut, in the order they are listed: one pair per
/// two commands that clash, so three on one chord make three pairs, and a command is never paired
/// with itself. Generic over the shortcut, so any `PartialEq` chord type (the crate's
/// [`Shortcut`](crate::Shortcut)) works and this module holds no engine type. The check does not
/// guess contexts: a command that is live in one mode only is the caller's to filter out first.
///
/// ```
/// use bevy_gooey::model::shortcut_conflicts;
/// let keymap = [("Save", "Ctrl+S"), ("Save all", "Ctrl+Shift+S"), ("Stash", "Ctrl+S")];
/// assert_eq!(shortcut_conflicts(&keymap), vec![("Save".to_owned(), "Stash".to_owned())]);
/// ```
pub fn shortcut_conflicts<S: PartialEq>(keymap: &[(&str, S)]) -> Vec<(String, String)> {
    let mut clashes = Vec::new();
    for (index, (first, shortcut)) in keymap.iter().enumerate() {
        for (second, other) in &keymap[index + 1..] {
            if shortcut == other {
                clashes.push(((*first).to_owned(), (*second).to_owned()));
            }
        }
    }
    clashes
}

/// A fuzzy match of `query` against `text`, higher is better, `None` when it does not match: how a
/// [`command palette`](crate::command_palette) ranks what the player typed ("opn prj") against
/// what a row says ("File: Open Project").
///
/// The query is split on whitespace and every term must occur in `text` as a subsequence, ignoring
/// case; the terms may match in any order. A term is aligned where it scores best: a point per
/// character, more for a character that starts a word (after a space or punctuation, or a capital
/// after a small letter) or follows the one before it, less for each character skipped between
/// two. The terms' scores add, and at the same alignment a shorter text outranks a longer. A query
/// with no terms matches everything, and only the length orders them.
///
/// ```
/// use bevy_gooey::model::fuzzy_score;
/// let open = fuzzy_score("opn prj", "Open Project").unwrap();
/// assert!(open > fuzzy_score("opn prj", "Reopen Project").unwrap());
/// assert!(fuzzy_score("opn prj", "Open Project Settings").unwrap() < open);
/// assert_eq!(fuzzy_score("xyz", "Open Project"), None);
/// ```
pub fn fuzzy_score(query: &str, text: &str) -> Option<u32> {
    const MATCH: i32 = 16;
    const WORD_START: i32 = 12;
    const CONSECUTIVE: i32 = 10;
    const GAP: i32 = 2;
    const LEAD_CAP: i32 = 4;
    const NO_MATCH: i32 = i32::MIN / 2;

    let chars: Vec<char> = text.chars().collect();
    let lower: Vec<char> = chars
        .iter()
        .map(|c| c.to_lowercase().next().unwrap_or(*c))
        .collect();
    let starts: Vec<bool> = chars
        .iter()
        .enumerate()
        .map(|(i, c)| {
            i == 0
                || !chars[i - 1].is_alphanumeric()
                || (c.is_uppercase() && chars[i - 1].is_lowercase())
        })
        .collect();

    let mut total: i32 = 0;
    for term in query.split_whitespace() {
        let term: Vec<char> = term
            .chars()
            .map(|c| c.to_lowercase().next().unwrap_or(c))
            .collect();
        // `prev[j]`: the best score of the term's characters so far with the last one at `j`.
        let mut prev = vec![NO_MATCH; chars.len()];
        for (i, wanted) in term.iter().enumerate() {
            let mut cur = vec![NO_MATCH; chars.len()];
            // The best way to have matched the characters before this one at least a gap away,
            // less the gap's cost, as the scan moves right.
            let mut gapped = NO_MATCH;
            for j in 0..chars.len() {
                if j >= 2 {
                    gapped = (gapped - GAP).max(prev[j - 2].saturating_sub(GAP));
                }
                if lower[j] != *wanted {
                    continue;
                }
                let here = MATCH + if starts[j] { WORD_START } else { 0 };
                let before = if i == 0 {
                    -(j as i32).min(LEAD_CAP)
                } else {
                    let next_to = if j >= 1 && prev[j - 1] > NO_MATCH {
                        prev[j - 1] + CONSECUTIVE
                    } else {
                        NO_MATCH
                    };
                    next_to.max(gapped)
                };
                if before > NO_MATCH {
                    cur[j] = here + before;
                }
            }
            prev = cur;
        }
        let best = prev.into_iter().max().filter(|&score| score > NO_MATCH)?;
        total += best.max(1);
    }
    let short = 255 - chars.len().min(255) as i32;
    Some(total.max(0) as u32 * 256 + short as u32)
}

/// `n` of a variant printed as `Other(n)`.
fn numbered(name: &str) -> Option<&str> {
    name.strip_prefix("Other(")?.strip_suffix(')')
}

/// A variant name cut into words at each capital that follows a lower-case letter or a digit:
/// "CapsLock" is "Caps Lock".
fn words(name: &str) -> String {
    let mut out = String::with_capacity(name.len() + 2);
    let mut before: Option<char> = None;
    for c in name.chars() {
        if c.is_uppercase() && before.is_some_and(|b| b.is_lowercase() || b.is_ascii_digit()) {
            out.push(' ');
        }
        out.push(c);
        before = Some(c);
    }
    out
}

/// How many repeats a held button has made between two moments, `held_before` and `held_now`
/// seconds after it went down: none until `delay`, then `per_second` a second, the first at
/// `delay` itself. The press itself is not a repeat. Zero for a delay or rate that is not usable.
///
/// ```
/// // Held 0.35 s then 0.45 s: the first repeat, at 0.4 s, falls in between.
/// assert_eq!(bevy_gooey::repeat_steps(0.35, 0.45, 0.4, 10.0), 1);
/// // Held through a whole second at once, delay 0.5 s: the repeats at 0.5, 0.6 … 1.0 s.
/// assert_eq!(bevy_gooey::repeat_steps(0.0, 1.0, 0.5, 10.0), 6);
/// ```
pub fn repeat_steps(held_before: f32, held_now: f32, delay: f32, per_second: f32) -> u32 {
    let due = |held: f32| {
        if held >= delay && held.is_finite() {
            ((held - delay) * per_second).floor() as u32 + 1
        } else {
            0
        }
    };
    let usable = |x: f32| x.is_finite() && x >= 0.0;
    if usable(delay) && per_second.is_finite() && per_second > 0.0 && held_now > held_before {
        due(held_now).saturating_sub(due(held_before))
    } else {
        0
    }
}

/// How long a toast stands fully shown, in seconds: `(base_seconds + characters ÷ chars_per_second)
/// × scale`. The reading time is the message's length at a reading speed (Netflix holds timed text to
/// 20 characters a second for adults), the base is the time to notice a thing at the edge of the eye,
/// and the scale is the player's own (Xbox Accessibility Guideline 116: adjustable up to at least ten
/// times the default).
///
/// Never negative, infinite or NaN: a base or a reading speed that is not finite and above zero
/// counts for nothing (no base, no reading time), and a scale that is not finite and above zero
/// gives no time at all.
///
/// ```
/// // "Game saved" at the defaults: 2 s to notice and half a second to read.
/// assert_eq!(bevy_gooey::toast_hold(10, 2.0, 20.0, 1.0), 2.5);
/// ```
pub fn toast_hold(characters: usize, base_seconds: f32, chars_per_second: f32, scale: f32) -> f32 {
    let usable = |x: f32| x.is_finite() && x > 0.0;
    let base = if usable(base_seconds) {
        base_seconds
    } else {
        0.0
    };
    let reading = if usable(chars_per_second) {
        characters as f32 / chars_per_second
    } else {
        0.0
    };
    if usable(scale) {
        (base + reading) * scale
    } else {
        0.0
    }
}

/// How long a toast lives in all: its fade in, `hold` fully shown and its fade out. A `fade` that is
/// not finite and above zero is no fade.
///
/// ```
/// assert_eq!(bevy_gooey::toast_life(2.5, 0.25), 3.0);
/// ```
pub fn toast_life(hold: f32, fade: f32) -> f32 {
    let fade = if fade.is_finite() && fade > 0.0 {
        fade
    } else {
        0.0
    };
    let hold = if hold.is_finite() && hold > 0.0 {
        hold
    } else {
        0.0
    };
    hold + 2.0 * fade
}

/// How opaque a toast is `age` seconds after it was spawned, from 0 to 1: rising over the first
/// `fade`, whole for `hold`, then falling over the last `fade` (see [`toast_life`]). With no fade
/// it is whole for `hold` and then gone. Never NaN: an age that is not finite or is negative reads
/// as not yet shown.
///
/// ```
/// assert_eq!(bevy_gooey::toast_alpha(0.0, 2.5, 0.25), 0.0);
/// assert_eq!(bevy_gooey::toast_alpha(1.0, 2.5, 0.25), 1.0);
/// assert_eq!(bevy_gooey::toast_alpha(3.0, 2.5, 0.25), 0.0);
/// ```
pub fn toast_alpha(age: f32, hold: f32, fade: f32) -> f32 {
    if !age.is_finite() || age < 0.0 {
        return 0.0;
    }
    let hold = if hold.is_finite() && hold > 0.0 {
        hold
    } else {
        0.0
    };
    if !(fade.is_finite() && fade > 0.0) {
        return if age < hold { 1.0 } else { 0.0 };
    }
    let rising = age / fade;
    let falling = (hold + 2.0 * fade - age) / fade;
    rising.min(falling).clamp(0.0, 1.0)
}

/// How much of its room a toast has opened `age` seconds after it was spawned, from 0 to 1: the
/// fade's envelope ([`toast_alpha`]) eased out (`1 − (1 − alpha)³`), so a new toast opens its room
/// quickly while it is still faint and settles, and a leaving one holds its room while it fades
/// and closes it at the end. The toasts around it glide with it, because the room is layout. With
/// no fade it is whole for `hold` and then gone.
///
/// ```
/// assert_eq!(bevy_gooey::toast_grow(0.0, 2.5, 0.25), 0.0);
/// assert_eq!(bevy_gooey::toast_grow(1.0, 2.5, 0.25), 1.0);
/// assert!(bevy_gooey::toast_grow(0.125, 2.5, 0.25) > 0.8);
/// ```
pub fn toast_grow(age: f32, hold: f32, fade: f32) -> f32 {
    let left = 1.0 - toast_alpha(age, hold, fade);
    1.0 - left * left * left
}

/// A time since the app started as a clock reads it: `m:ss`, and `h:mm:ss` from an hour. A time that
/// is not finite or is negative reads as zero.
///
/// ```
/// assert_eq!(bevy_gooey::clock_text(7.4), "0:07");
/// assert_eq!(bevy_gooey::clock_text(754.0), "12:34");
/// assert_eq!(bevy_gooey::clock_text(3723.0), "1:02:03");
/// assert_eq!(bevy_gooey::clock_text(f32::NAN), "0:00");
/// ```
pub fn clock_text(seconds: f32) -> String {
    let total = if seconds.is_finite() && seconds > 0.0 {
        seconds as u64
    } else {
        0
    };
    let (hours, minutes, secs) = (total / 3600, total / 60 % 60, total % 60);
    if hours > 0 {
        format!("{hours}:{minutes:02}:{secs:02}")
    } else {
        format!("{minutes}:{secs:02}")
    }
}

/// How tall a list stands to show `rows` rows, in the units of its inputs: `rows × (row + gap)`,
/// `row` the height of one row and `gap` the space between two, so each row counts with the gap
/// after it. `4.5` is four rows and half a pitch of the fifth, which cuts it, the signifier that
/// more is below (NN/g, *Scrolling and Attention*); `4.0` ends a gap past the fourth row. Zero for
/// a count that is not finite and above zero.
///
/// ```
/// // Four and a half rows of 48 px with 10 px between: four rows and 29 px of the fifth.
/// assert_eq!(bevy_gooey::list_height(4.5, 48.0, 10.0), 4.5 * 58.0);
/// assert_eq!(bevy_gooey::list_height(4.0, 48.0, 10.0), 4.0 * 58.0);
/// assert_eq!(bevy_gooey::list_height(f32::NAN, 48.0, 10.0), 0.0);
/// ```
pub fn list_height(rows: f32, row: f32, gap: f32) -> f32 {
    if rows.is_finite() && rows > 0.0 && row.is_finite() && gap.is_finite() {
        (rows * (row + gap)).max(0.0)
    } else {
        0.0
    }
}

/// The scroll position that brings a span into a list's viewport with context round it, measured
/// from the start of the scrolled content: the span `top..bottom` (a focused widget), a viewport
/// `view` tall at `scroll`, a furthest scroll `max`, and `margin` of list to leave beyond the span.
///
/// The least scroll that leaves `margin` of list on the side the span would leave through, so the
/// player always sees what is next (revealing only to the edge glues the focus to the bottom pixel
/// of the viewport with nothing in sight below it). The margin is cut to what the viewport can hold
/// beside the span. A span taller than the viewport scrolls to its top, the part read first; a move
/// of more than one viewport centres the span instead of creeping to the edge; the answer is
/// always within `0..=max`, and `scroll` itself when the span is already comfortably inside.
/// Nothing usable (a viewport of no height, a value that is not finite) leaves `scroll` alone.
///
/// ```
/// // A 160 px viewport at the top of a 440 px list of 40 px rows, a margin of one row: the fourth
/// // row (120..160) wants the fifth in sight too, 160 + 40 − 160 = 40 px of scroll, and from there
/// // the fifth (160..200) wants 200 + 40 − 160 = 80.
/// assert_eq!(bevy_gooey::scroll_to_reveal(120.0, 160.0, 160.0, 0.0, 280.0, 40.0), 40.0);
/// assert_eq!(bevy_gooey::scroll_to_reveal(160.0, 200.0, 160.0, 40.0, 280.0, 40.0), 80.0);
/// // The third row (80..120) already has a row below it in view: nothing to do.
/// assert_eq!(bevy_gooey::scroll_to_reveal(80.0, 120.0, 160.0, 0.0, 280.0, 40.0), 0.0);
/// // The last row stops at the end of the list, not a margin past it.
/// assert_eq!(bevy_gooey::scroll_to_reveal(400.0, 440.0, 160.0, 200.0, 280.0, 40.0), 280.0);
/// ```
pub fn scroll_to_reveal(
    top: f32,
    bottom: f32,
    view: f32,
    scroll: f32,
    max: f32,
    margin: f32,
) -> f32 {
    let usable = [top, bottom, view, scroll, max, margin]
        .iter()
        .all(|x| x.is_finite());
    let max = max.max(0.0);
    if !usable || view <= 0.0 || bottom < top {
        return if scroll.is_finite() {
            scroll.clamp(0.0, max)
        } else {
            0.0
        };
    }
    let height = bottom - top;
    // A span taller than the viewport is read from its top, whichever way it is reached.
    if height > view {
        return top.clamp(0.0, max);
    }
    // What the viewport can hold beside the span, so a short viewport asks for the most margin it
    // can keep rather than a margin on each side it cannot have both of.
    let margin = margin.max(0.0).min((view - height) * 0.5);
    let want = if top - margin < scroll {
        top - margin
    } else if bottom + margin > scroll + view {
        bottom + margin - view
    } else {
        scroll
    };
    // Further than a viewport is a jump, not a step: put the span in the middle.
    let want = if (want - scroll).abs() > view {
        (top + bottom) * 0.5 - view * 0.5
    } else {
        want
    };
    want.clamp(0.0, max)
}

/// A scroll position moved on to the top of a row, so a list that follows focus always stands with a
/// row flush at the top of its viewport, as it does at rest, and the row it cuts at the bottom is
/// cut the same way at every step: `want` is where [`scroll_to_reveal`] asked to go from `scroll`,
/// and `tops` are the rows' tops in the same units. Moving down it takes the first row top at or
/// after `want`, moving up the last at or before it (half a unit of slack for rounded layout), so
/// it never scrolls less than was asked. `None` when no row top lies that way (the end of the
/// list: the caller keeps `want`, which then ends flush with the last row) or `want` is no move.
///
/// ```
/// let tops = [0.0, 57.0, 114.0, 171.0];
/// // A step of 46.8 down, from the top, goes on to the next row's top.
/// assert_eq!(bevy_gooey::snap_to_row(46.8, 0.0, &tops), Some(57.0));
/// // A step up from 171 that asks for 120 stops at the row top above it.
/// assert_eq!(bevy_gooey::snap_to_row(120.0, 171.0, &tops), Some(114.0));
/// // Past the last row top there is nothing to snap to.
/// assert_eq!(bevy_gooey::snap_to_row(190.0, 114.0, &tops), None);
/// ```
pub fn snap_to_row(want: f32, scroll: f32, tops: &[f32]) -> Option<f32> {
    if !(want.is_finite() && scroll.is_finite()) || (want - scroll).abs() < f32::EPSILON {
        return None;
    }
    let usable = tops.iter().copied().filter(|t| t.is_finite());
    if want > scroll {
        usable
            .filter(|&t| t >= want - 0.5)
            .min_by(|a, b| a.total_cmp(b))
    } else {
        usable
            .filter(|&t| t <= want + 0.5)
            .max_by(|a, b| a.total_cmp(b))
    }
}

/// Which of a list's rows a page away from the focused one is, for PageUp and PageDown: `from` is
/// the focused row's centre along the list, `centres` the rows' centres in the same units, and
/// `page` how far to go, positive for down and negative for up. The row furthest from `from` in
/// that direction that is still within a page of it; if even the next row is further than a page
/// away (tall rows), the next row. `None` when no row lies that way. Rows less than half a unit
/// from `from` count as its own row; of rows at one distance the first is taken.
///
/// ```
/// let rows = [20.0, 70.0, 120.0, 170.0, 220.0, 270.0];
/// // From the first row, a 150-unit page lands on the row at 170.
/// assert_eq!(bevy_gooey::page_target(20.0, &rows, 150.0), Some(3));
/// // Up from the last row, the same page lands on the row at 120.
/// assert_eq!(bevy_gooey::page_target(270.0, &rows, -150.0), Some(2));
/// // Nothing lies below the last row.
/// assert_eq!(bevy_gooey::page_target(270.0, &rows, 150.0), None);
/// // A page shorter than the pitch still takes one step.
/// assert_eq!(bevy_gooey::page_target(20.0, &rows, 10.0), Some(1));
/// ```
pub fn page_target(from: f32, centres: &[f32], page: f32) -> Option<usize> {
    if !(from.is_finite() && page.is_finite() && page != 0.0) {
        return None;
    }
    let ahead = |centre: f32| (centre - from) * page.signum();
    let mut nearest: Option<(usize, f32)> = None;
    let mut farthest: Option<(usize, f32)> = None;
    for (i, &centre) in centres.iter().enumerate() {
        let d = ahead(centre);
        if d.is_nan() || d < 0.5 {
            continue;
        }
        if nearest.is_none_or(|(_, n)| d < n) {
            nearest = Some((i, d));
        }
        if d <= page.abs() && farthest.is_none_or(|(_, f)| d > f) {
            farthest = Some((i, d));
        }
    }
    farthest.or(nearest).map(|(i, _)| i)
}

/// How far a key moves a [`crate::split`]'s divider, in logical pixels: an arrow press steps by this,
/// and a held key repeats. A design default: a pane's edge is a pixel thing, and a step the size of
/// a gap is visible and reaches any size in a few presses.
pub const SPLIT_KEY_STEP_PX: f32 = 16.0;

/// The smallest sizes, in logical pixels, a [`crate::split`]'s two panes may have in `extent`
/// pixels (the split's length less its divider), as `(first, second)`. The minimums asked for
/// when they fit; when `extent` is smaller than the two together, the second pane gives way first
/// down to nothing and the first keeps its own minimum while it can. Negative and non-finite
/// inputs count as zero.
///
/// ```
/// assert_eq!(bevy_gooey::split_mins(500.0, 100.0, 80.0), (100.0, 80.0));
/// // 150 px cannot hold both: the second side collapses first.
/// assert_eq!(bevy_gooey::split_mins(150.0, 100.0, 80.0), (100.0, 50.0));
/// assert_eq!(bevy_gooey::split_mins(60.0, 100.0, 80.0), (60.0, 0.0));
/// ```
pub fn split_mins(extent: f32, min_first: f32, min_second: f32) -> (f32, f32) {
    let usable = |x: f32| if x.is_finite() { x.max(0.0) } else { 0.0 };
    let extent = usable(extent);
    let first = usable(min_first).min(extent);
    let second = usable(min_second).min(extent - first);
    (first, second)
}

/// A [`crate::split`]'s fraction held to its panes' minimums: `fraction` (the first pane's share
/// of `extent`) clamped to the range [`split_mins`] leaves, and to 0 to 1. Never NaN; with no room
/// (`extent` zero or less) only the 0 to 1 clamp applies.
///
/// ```
/// // 400 px of room, minimums 100 and 80: the first pane's share stays within 0.25 and 0.8.
/// assert_eq!(bevy_gooey::split_clamp(0.1, 400.0, 100.0, 80.0), 0.25);
/// assert_eq!(bevy_gooey::split_clamp(0.9, 400.0, 100.0, 80.0), 0.8);
/// assert_eq!(bevy_gooey::split_clamp(0.5, 400.0, 100.0, 80.0), 0.5);
/// ```
pub fn split_clamp(fraction: f32, extent: f32, min_first: f32, min_second: f32) -> f32 {
    let fraction = if fraction.is_finite() {
        fraction.clamp(0.0, 1.0)
    } else {
        0.0
    };
    if !(extent.is_finite() && extent > 0.0) {
        return fraction;
    }
    let (first, second) = split_mins(extent, min_first, min_second);
    fraction.clamp(first / extent, 1.0 - second / extent)
}

/// Where a [`crate::split`]'s fraction lands when a divider that started at `start` is moved
/// `distance` logical pixels along the split's axis: `start + distance / extent`, held to the
/// minimums ([`split_clamp`]). A drag of 100 px changes the fraction by `100 / extent`.
///
/// ```
/// let moved = bevy_gooey::split_drag(0.5, 100.0, 800.0, 0.0, 0.0);
/// assert!((moved - 0.625).abs() < 1e-6);
/// // Dragged a long way past the end it stops at the second pane's minimum.
/// assert_eq!(bevy_gooey::split_drag(0.5, 5000.0, 800.0, 0.0, 200.0), 0.75);
/// ```
pub fn split_drag(start: f32, distance: f32, extent: f32, min_first: f32, min_second: f32) -> f32 {
    if extent.is_finite() && extent > 0.0 && distance.is_finite() {
        split_clamp(start + distance / extent, extent, min_first, min_second)
    } else {
        split_clamp(start, extent, min_first, min_second)
    }
}

/// The least a pane of a [`crate::dock`]'s split may be, in logical pixels: a panel narrower than
/// this is worse than none, and a drop that made one could not be undone by a drag.
pub const DOCK_PANE_MIN_PX: f32 = 96.0;

/// How much of a group's width or height, at each end, is an edge for [`dock_zone`]: the outer
/// quarter is an edge, the middle half is the group.
pub const DOCK_EDGE_FRACTION: f32 = 0.25;

/// The share of a whole dock a panel dropped on its edge takes ([`dock_drop_rect`]).
pub const DOCK_EDGE_SHARE: f32 = 0.25;

/// Where a dragged panel of a [`crate::dock`] lands relative to a group: into it, or against one of
/// its edges (a split of the group on that side).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
pub enum DockZone {
    /// Into the group, as one of its tabs.
    Into,
    /// A group of its own to the left.
    Left,
    /// A group of its own to the right.
    Right,
    /// A group of its own above.
    Top,
    /// A group of its own below.
    Bottom,
}

/// The zone of a group `width` by `height` that the point `(x, y)`, from the group's top-left, is
/// in: the middle half of both sides is [`DockZone::Into`], and anywhere else the edge nearest the
/// point (by its share of the side). A degenerate group is all `Into`.
///
/// ```
/// use bevy_gooey::{DockZone, dock_zone};
/// assert_eq!(dock_zone(400.0, 200.0, 200.0, 100.0), DockZone::Into);
/// assert_eq!(dock_zone(400.0, 200.0, 20.0, 100.0), DockZone::Left);
/// assert_eq!(dock_zone(400.0, 200.0, 200.0, 190.0), DockZone::Bottom);
/// ```
pub fn dock_zone(width: f32, height: f32, x: f32, y: f32) -> DockZone {
    if !(width > 0.0 && height > 0.0 && x.is_finite() && y.is_finite()) {
        return DockZone::Into;
    }
    let (nx, ny) = ((x / width).clamp(0.0, 1.0), (y / height).clamp(0.0, 1.0));
    let edge = DOCK_EDGE_FRACTION;
    if (edge..=1.0 - edge).contains(&nx) && (edge..=1.0 - edge).contains(&ny) {
        return DockZone::Into;
    }
    let nearest = [
        (nx, DockZone::Left),
        (1.0 - nx, DockZone::Right),
        (ny, DockZone::Top),
        (1.0 - ny, DockZone::Bottom),
    ];
    nearest
        .into_iter()
        .fold((f32::MAX, DockZone::Into), |best, now| {
            if now.0 < best.0 { now } else { best }
        })
        .1
}

/// The edge of a whole dock `width` by `height` that the point `(x, y)` is within `band` of, the
/// nearest if two (a corner), or `None` away from every edge (or outside the dock). Dropping on
/// one splits the whole layout rather than a group.
///
/// ```
/// use bevy_gooey::{DockZone, dock_edge_zone};
/// assert_eq!(dock_edge_zone(800.0, 400.0, 10.0, 200.0, 24.0), Some(DockZone::Left));
/// assert_eq!(dock_edge_zone(800.0, 400.0, 400.0, 200.0, 24.0), None);
/// ```
pub fn dock_edge_zone(width: f32, height: f32, x: f32, y: f32, band: f32) -> Option<DockZone> {
    if !(x >= 0.0 && y >= 0.0 && x <= width && y <= height) {
        return None;
    }
    [
        (x, DockZone::Left),
        (width - x, DockZone::Right),
        (y, DockZone::Top),
        (height - y, DockZone::Bottom),
    ]
    .into_iter()
    .filter(|(distance, _)| *distance < band)
    .min_by(|a, b| a.0.total_cmp(&b.0))
    .map(|(_, zone)| zone)
}

/// The part of a group (or, with `whole`, of the whole dock) `width` by `height` that a panel
/// dropped in `zone` will take, as `(x, y, width, height)` from the top-left: all of the group for
/// [`DockZone::Into`], half of it for an edge ([`DOCK_EDGE_SHARE`] of the whole dock). The overlay
/// that shows the landing is drawn from it, so it is exactly the layout the drop makes.
pub fn dock_drop_rect(
    zone: DockZone,
    width: f32,
    height: f32,
    whole: bool,
) -> (f32, f32, f32, f32) {
    let share = if whole { DOCK_EDGE_SHARE } else { 0.5 };
    match zone {
        DockZone::Into => (0.0, 0.0, width, height),
        DockZone::Left => (0.0, 0.0, width * share, height),
        DockZone::Right => (width * (1.0 - share), 0.0, width * share, height),
        DockZone::Top => (0.0, 0.0, width, height * share),
        DockZone::Bottom => (0.0, height * (1.0 - share), width, height * share),
    }
}

/// The place among a group's tabs a panel dropped at `(x, y)` lands in, for tabs that may stand in
/// several rows: `tabs` are each tab's `(centre x, top, bottom)` in order, and a tab is before the
/// point when it lies wholly above it, or is in the point's row and its centre is left of `x`. `0`
/// is before the first tab and `tabs.len()` after the last.
///
/// ```
/// let row = [(50.0, 0.0, 40.0), (150.0, 0.0, 40.0), (250.0, 0.0, 40.0)];
/// assert_eq!(bevy_gooey::dock_tab_slot(&row, 160.0, 20.0), 2);
/// assert_eq!(bevy_gooey::dock_tab_slot(&[], 10.0, 10.0), 0);
/// // A second row: a point in it is after the whole first row.
/// let two = [(50.0, 0.0, 40.0), (150.0, 0.0, 40.0), (50.0, 46.0, 86.0)];
/// assert_eq!(bevy_gooey::dock_tab_slot(&two, 20.0, 60.0), 2);
/// ```
pub fn dock_tab_slot(tabs: &[(f32, f32, f32)], x: f32, y: f32) -> usize {
    tabs.iter()
        .filter(|&&(centre, _, bottom)| bottom <= y || (centre < x && y < bottom))
        .count()
}

/// The one of `others` (centres of groups) nearest to `from`, in the direction `toward` names
/// (an edge zone; [`DockZone::Into`] has no direction), or `None` when none lies that way. A group
/// off to the side counts against the one straight ahead: distance along the direction, with
/// twice the sideways distance.
///
/// ```
/// use bevy_gooey::{DockZone, dock_neighbour};
/// let others = [(100.0, 50.0), (400.0, 60.0), (400.0, 300.0)];
/// assert_eq!(dock_neighbour((200.0, 50.0), &others, DockZone::Right), Some(1));
/// assert_eq!(dock_neighbour((200.0, 50.0), &others, DockZone::Top), None);
/// ```
pub fn dock_neighbour(from: (f32, f32), others: &[(f32, f32)], toward: DockZone) -> Option<usize> {
    let (dx, dy) = match toward {
        DockZone::Into => return None,
        DockZone::Left => (-1.0, 0.0),
        DockZone::Right => (1.0, 0.0),
        DockZone::Top => (0.0, -1.0),
        DockZone::Bottom => (0.0, 1.0),
    };
    others
        .iter()
        .enumerate()
        .filter_map(|(index, &(x, y))| {
            let (vx, vy) = (x - from.0, y - from.1);
            let ahead = vx * dx + vy * dy;
            let aside = vx * dy - vy * dx;
            (ahead > 1.0).then_some((index, ahead * ahead + 4.0 * aside * aside))
        })
        .min_by(|a, b| a.1.total_cmp(&b.1))
        .map(|(index, _)| index)
}

/// The order of two cells' text for a table's sort: runs of digits compare by value ("2" before
/// "10", "007" the same number as "7"), everything else letter by letter without regard to case,
/// and what is still equal falls back to the exact bytes, so the order is total and stable.
///
/// ```
/// use std::cmp::Ordering::{Equal, Greater, Less};
/// assert_eq!(bevy_gooey::natural_cmp("Item 2", "Item 10"), Less);
/// assert_eq!(bevy_gooey::natural_cmp("item 10", "Item 2"), Greater);
/// assert_eq!(bevy_gooey::natural_cmp("apple", "Banana"), Less);
/// assert_eq!(bevy_gooey::natural_cmp("a", "a"), Equal);
/// ```
pub fn natural_cmp(a: &str, b: &str) -> std::cmp::Ordering {
    use std::cmp::Ordering;
    // The digits at the start of `s` (ASCII, so a byte length is a char length), without the
    // zeros that lead them.
    fn digits(s: &str) -> (&str, usize) {
        let run = s.bytes().take_while(u8::is_ascii_digit).count();
        (s[..run].trim_start_matches('0'), run)
    }
    let (mut x, mut y) = (a, b);
    loop {
        match (x.chars().next(), y.chars().next()) {
            (None, None) => return a.cmp(b),
            (None, Some(_)) => return Ordering::Less,
            (Some(_), None) => return Ordering::Greater,
            (Some(p), Some(q)) if p.is_ascii_digit() && q.is_ascii_digit() => {
                let ((m, taken_x), (n, taken_y)) = (digits(x), digits(y));
                let order = m.len().cmp(&n.len()).then_with(|| m.cmp(n));
                if order != Ordering::Equal {
                    return order;
                }
                (x, y) = (&x[taken_x..], &y[taken_y..]);
            }
            (Some(p), Some(q)) => {
                let order = p.to_lowercase().cmp(q.to_lowercase());
                if order != Ordering::Equal {
                    return order;
                }
                (x, y) = (&x[p.len_utf8()..], &y[q.len_utf8()..]);
            }
        }
    }
}

/// The first row a virtualized table draws: the row the `scroll` offset has at its top, held so
/// that `pool` rows from it are all rows (`len` rows in all, each `pitch` tall). A scroll past the
/// end, a pool larger than the data or a pitch that is not usable answer with a valid first row.
///
/// ```
/// assert_eq!(bevy_gooey::table_window(0.0, 40.0, 10, 1000), 0);
/// assert_eq!(bevy_gooey::table_window(400.0, 40.0, 10, 1000), 10);
/// assert_eq!(bevy_gooey::table_window(399.0, 40.0, 10, 1000), 9);
/// // The last rows: the pool never runs past the data.
/// assert_eq!(bevy_gooey::table_window(1e9, 40.0, 10, 1000), 990);
/// assert_eq!(bevy_gooey::table_window(400.0, 40.0, 10, 4), 0);
/// assert_eq!(bevy_gooey::table_window(f32::NAN, 40.0, 10, 1000), 0);
/// ```
pub fn table_window(scroll: f32, pitch: f32, pool: usize, len: usize) -> usize {
    let last = len.saturating_sub(pool);
    if !(scroll.is_finite() && pitch.is_finite()) || pitch <= 0.0 || scroll <= 0.0 {
        return 0;
    }
    ((scroll / pitch).floor() as usize).min(last)
}

/// A move of a table's cursor row.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum TableStep {
    /// One row up.
    Up,
    /// One row down.
    Down,
    /// A page up.
    PageUp,
    /// A page down.
    PageDown,
    /// The first row of the data.
    First,
    /// The last row of the data, not of the rows drawn.
    Last,
}

/// Where a table's cursor goes: from display row `from` (none yet) by `step`, in `len` rows with
/// `page` rows to a page. Never past either end; `None` when there are no rows. With no cursor
/// yet, any step but Up and PageUp lands on the first row and those two on the last, so the first
/// key press lands somewhere in sight of where the player was going.
///
/// ```
/// use bevy_gooey::TableStep::*;
/// assert_eq!(bevy_gooey::table_step(Some(5), Down, 10, 4), Some(6));
/// assert_eq!(bevy_gooey::table_step(Some(9), Down, 10, 4), Some(9));
/// assert_eq!(bevy_gooey::table_step(Some(5), PageDown, 10, 4), Some(9));
/// assert_eq!(bevy_gooey::table_step(Some(2), PageUp, 10, 4), Some(0));
/// assert_eq!(bevy_gooey::table_step(Some(2), Last, 10_000, 4), Some(9_999));
/// assert_eq!(bevy_gooey::table_step(None, Down, 10, 4), Some(0));
/// assert_eq!(bevy_gooey::table_step(None, Up, 10, 4), Some(9));
/// assert_eq!(bevy_gooey::table_step(Some(0), Down, 0, 4), None);
/// ```
pub fn table_step(from: Option<usize>, step: TableStep, len: usize, page: usize) -> Option<usize> {
    let last = len.checked_sub(1)?;
    let page = page.max(1);
    let Some(from) = from.map(|f| f.min(last)) else {
        return Some(match step {
            TableStep::Up | TableStep::PageUp | TableStep::Last => last,
            TableStep::Down | TableStep::PageDown | TableStep::First => 0,
        });
    };
    Some(match step {
        TableStep::Up => from.saturating_sub(1),
        TableStep::Down => (from + 1).min(last),
        TableStep::PageUp => from.saturating_sub(page),
        TableStep::PageDown => (from + page).min(last),
        TableStep::First => 0,
        TableStep::Last => last,
    })
}

/// The scroll that keeps a table's anchor row where it stood when its rows change under it: the
/// row that was `old_first` at the top of the view, `scroll` pixels down, is now display row
/// `new_index` (`None`: it is gone, so the scroll stays), `pitch` pixels to a row, held to `max`.
///
/// ```
/// // 100 rows come in above the row that was at the top, 5 px into row 50.
/// assert_eq!(bevy_gooey::table_anchor(2005.0, 40.0, 50, Some(150), 1e9), 6005.0);
/// // The anchor row is gone: stay.
/// assert_eq!(bevy_gooey::table_anchor(2005.0, 40.0, 50, None, 1e9), 2005.0);
/// // Held to the end of the data.
/// assert_eq!(bevy_gooey::table_anchor(2005.0, 40.0, 50, Some(150), 3000.0), 3000.0);
/// ```
pub fn table_anchor(
    scroll: f32,
    pitch: f32,
    old_first: usize,
    new_index: Option<usize>,
    max: f32,
) -> f32 {
    let moved = new_index.map_or(scroll, |new| {
        scroll + (new as f32 - old_first as f32) * pitch
    });
    if moved.is_finite() {
        moved.clamp(0.0, max.max(0.0))
    } else {
        0.0
    }
}

/// The least a table's column may be, in body text sizes: room for a letter and a sort mark.
pub const TABLE_LEAST_COLUMN: f32 = 3.0;

/// A column's width after its edge moves `by` pixels from `start` (all in logical pixels), never
/// under `least`.
///
/// ```
/// assert_eq!(bevy_gooey::column_resize(100.0, 40.0, 48.0), 140.0);
/// assert_eq!(bevy_gooey::column_resize(100.0, -90.0, 48.0), 48.0);
/// assert_eq!(bevy_gooey::column_resize(100.0, f32::NAN, 48.0), 100.0);
/// ```
pub fn column_resize(start: f32, by: f32, least: f32) -> f32 {
    let wide = start + by;
    if wide.is_finite() {
        wide.max(least)
    } else {
        start.max(least)
    }
}

/// How long a pause ends a typed prefix, in seconds: characters typed within this long of each
/// other make one prefix (the APG's "rapid succession"), a longer pause starts it over.
pub const TYPE_AHEAD_SECS: f32 = 1.0;

/// The indent of one tree level, and the width of a node's disclosure chevron, in logical pixels
/// for body text `text_px` high: a text size and a half, never under [`MIN_TARGET_PX`] (WCAG 2.5.8).
///
/// ```
/// assert_eq!(bevy_gooey::tree_indent(16.0), 24.0);
/// assert_eq!(bevy_gooey::tree_indent(32.0), 48.0);
/// assert_eq!(bevy_gooey::tree_indent(10.0), 24.0);
/// ```
pub fn tree_indent(text_px: f32) -> f32 {
    (text_px * 1.5).max(MIN_TARGET_PX)
}

/// For nodes in depth-first order with the given `depths` (the first is 0 and no depth is more
/// than one past the one before it), where each node's subtree ends: the index of the first node
/// after it that is not its descendant (`depths.len()` for the last subtree). A node with no
/// children ends at the next index.
///
/// ```
/// // a ( b ( c ) d ) e
/// assert_eq!(bevy_gooey::tree_ends(&[0, 1, 2, 1, 0]), vec![4, 3, 3, 4, 5]);
/// ```
pub fn tree_ends(depths: &[u32]) -> Vec<usize> {
    let mut ends = vec![depths.len(); depths.len()];
    let mut open: Vec<usize> = Vec::new();
    for (i, &depth) in depths.iter().enumerate() {
        while let Some(&top) = open.last() {
            if depths[top] < depth {
                break;
            }
            ends[top] = i;
            open.pop();
        }
        open.push(i);
    }
    ends
}

/// The nodes a tree shows, in order: every node whose ancestors are all open. `ends` is
/// [`tree_ends`] and `open` each node's own state; a closed node's descendants are skipped
/// whatever their own state, so closing a node loses nothing below it.
///
/// ```
/// let ends = bevy_gooey::tree_ends(&[0, 1, 2, 1, 0]);
/// // a is open, b is closed (c is open but hidden), e is closed.
/// let open = [true, false, true, false, false];
/// assert_eq!(bevy_gooey::tree_visible(&ends, &open), vec![0, 1, 3, 4]);
/// ```
pub fn tree_visible(ends: &[usize], open: &[bool]) -> Vec<usize> {
    let mut shown = Vec::new();
    let mut i = 0;
    while i < ends.len() {
        shown.push(i);
        i = if open.get(i).copied().unwrap_or(false) {
            i + 1
        } else {
            ends[i]
        };
    }
    shown
}

/// The parent of node `index`: the nearest node before it that is shallower. `None` for a root.
///
/// ```
/// let depths = [0, 1, 2, 1, 0];
/// assert_eq!(bevy_gooey::tree_parent(&depths, 2), Some(1));
/// assert_eq!(bevy_gooey::tree_parent(&depths, 3), Some(0));
/// assert_eq!(bevy_gooey::tree_parent(&depths, 4), None);
/// ```
pub fn tree_parent(depths: &[u32], index: usize) -> Option<usize> {
    let depth = *depths.get(index)?;
    (0..index).rev().find(|&j| depths[j] < depth)
}

/// Who takes the place of node `index` when its subtree is removed: its next sibling, else its
/// previous sibling, else its parent. `None` for the only node there is.
///
/// ```
/// // a ( b c ) d ( e )
/// let depths = [0, 1, 1, 0, 1];
/// let ends = bevy_gooey::tree_ends(&depths);
/// assert_eq!(bevy_gooey::tree_heir(&depths, &ends, 1), Some(2)); // next sibling
/// assert_eq!(bevy_gooey::tree_heir(&depths, &ends, 2), Some(1)); // the one before
/// assert_eq!(bevy_gooey::tree_heir(&depths, &ends, 4), Some(3)); // an only child: the parent
/// assert_eq!(bevy_gooey::tree_heir(&depths, &ends, 0), Some(3)); // a root: the next root
/// assert_eq!(bevy_gooey::tree_heir(&[0], &[1], 0), None);
/// ```
pub fn tree_heir(depths: &[u32], ends: &[usize], index: usize) -> Option<usize> {
    let depth = *depths.get(index)?;
    let next = *ends.get(index)?;
    if depths.get(next) == Some(&depth) {
        return Some(next);
    }
    (0..index).rev().find(|&j| depths[j] <= depth)
}

/// Where type-ahead takes the cursor: in `len` rows with the cursor on `from`, the first row that
/// `hit` accepts, looking forward and wrapping. A one-character prefix starts after the cursor row
/// (typing "c" again goes on to the next row starting with "c"); a longer one starts on it (typing
/// "ca" while on "Camera" stays). `None` when no row matches.
///
/// ```
/// let rows = ["Camera", "Cube", "Light", "Cube2"];
/// let hit = |prefix: &'static str| move |i: usize| rows[i].to_lowercase().starts_with(prefix);
/// assert_eq!(bevy_gooey::type_ahead(4, None, 1, hit("c")), Some(0));
/// assert_eq!(bevy_gooey::type_ahead(4, Some(0), 1, hit("c")), Some(1));
/// assert_eq!(bevy_gooey::type_ahead(4, Some(3), 1, hit("c")), Some(0));
/// assert_eq!(bevy_gooey::type_ahead(4, Some(1), 2, hit("cu")), Some(1));
/// assert_eq!(bevy_gooey::type_ahead(4, Some(1), 1, hit("z")), None);
/// ```
pub fn type_ahead(
    len: usize,
    from: Option<usize>,
    prefix_len: usize,
    hit: impl Fn(usize) -> bool,
) -> Option<usize> {
    let start = match from {
        None => 0,
        Some(f) if prefix_len <= 1 => f + 1,
        Some(f) => f,
    };
    (0..len).map(|k| (start + k) % len.max(1)).find(|&i| hit(i))
}

/// Why [`parse_number`] would not read some text as a number. The words are for the player
/// ([`std::fmt::Display`]): a game shows them beside the field, the crate sends them with
/// [`crate::NumberRefused`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub enum NumberError {
    /// Nothing was typed.
    Empty,
    /// An expression such as `1.5*2`: a number field takes a number, not a sum.
    Expression,
    /// Letters, or digits in the wrong places.
    NotANumber,
    /// A number too large to hold, or `inf` or `NaN`.
    NotFinite,
}

impl std::fmt::Display for NumberError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(match self {
            Self::Empty => "type a number",
            Self::Expression => "type a number, not an expression",
            Self::NotANumber => "that is not a number",
            Self::NotFinite => "that number is too large",
        })
    }
}

/// The number a player typed: spaces round it are ignored, a leading `+`, `-` or `−` (U+2212) is
/// a sign, and a decimal point and an exponent (`1e3`) are read; the decimal comma is not. An
/// expression (`1.5*2`, `3+4`, `(2)`) is refused as [`NumberError::Expression`], never evaluated.
///
/// ```
/// use bevy_gooey::{NumberError, parse_number};
/// assert_eq!(parse_number(" 2.5 "), Ok(2.5));
/// assert_eq!(parse_number("−3"), Ok(-3.0));
/// assert_eq!(parse_number("1e3"), Ok(1000.0));
/// assert_eq!(parse_number("1.5*2"), Err(NumberError::Expression));
/// assert_eq!(parse_number("abc"), Err(NumberError::NotANumber));
/// assert_eq!(parse_number(""), Err(NumberError::Empty));
/// ```
pub fn parse_number(text: &str) -> Result<f32, NumberError> {
    let text = text.trim();
    if text.is_empty() {
        return Err(NumberError::Empty);
    }
    let text = text.replace('\u{2212}', "-");
    let mut previous = None;
    for (i, c) in text.char_indices() {
        let sign = matches!(c, '+' | '-');
        let exponent_sign = sign && matches!(previous, Some('e' | 'E'));
        if matches!(c, '*' | '/' | '(' | ')' | '^' | '%' | '\u{d7}' | '\u{f7}')
            || (sign && i > 0 && !exponent_sign)
        {
            return Err(NumberError::Expression);
        }
        previous = Some(c);
    }
    match text.parse::<f32>() {
        Ok(n) if n.is_finite() => Ok(n),
        Ok(_) => Err(NumberError::NotFinite),
        Err(_) => Err(NumberError::NotANumber),
    }
}

/// The digits after the point that show every multiple of `step` exactly: 1 for 0.1, 2 for 0.25,
/// 0 for 1 or 5, at most 6. A step that is not a positive number shows 2.
///
/// ```
/// assert_eq!(bevy_gooey::number_decimals(0.1), 1);
/// assert_eq!(bevy_gooey::number_decimals(0.25), 2);
/// assert_eq!(bevy_gooey::number_decimals(5.0), 0);
/// ```
pub fn number_decimals(step: f32) -> usize {
    if !(step.is_finite() && step > 0.0) {
        return 2;
    }
    (0..=6)
        .find(|&d| {
            let scale = 10f32.powi(d);
            ((step * scale).round() / scale - step).abs() <= step * 1e-4
        })
        .map_or(6, |d| d as usize)
}

/// A number as a field shows it: the digits of `step` (see [`number_decimals`]) and more when the
/// value needs them (the fewest, up to 6, that read back as the same number), so the text never
/// says a different number than the value. Never `-0`.
///
/// ```
/// assert_eq!(bevy_gooey::format_number(5.0, 0.1), "5.0");
/// assert_eq!(bevy_gooey::format_number(1.55, 0.1), "1.55");
/// assert_eq!(bevy_gooey::format_number(-0.0, 0.1), "0.0");
/// assert_eq!(bevy_gooey::format_number(42.0, 1.0), "42");
/// ```
pub fn format_number(value: f32, step: f32) -> String {
    let base = number_decimals(step);
    if !value.is_finite() {
        return format!("{value}");
    }
    let value = if value == 0.0 { 0.0 } else { value };
    (base..=6)
        .map(|d| format!("{value:.d$}"))
        .find(|s| s.parse::<f32>().is_ok_and(|n| n == value))
        .unwrap_or_else(|| format!("{value:.6}"))
}

/// What a drag of `distance` logical pixels makes of a number that was `start` when the press
/// began: `start + distance × step`, so 50 px at a step of 0.1 is 5.0. `fine` (Shift) takes a
/// tenth of the rate and `coarse` (Ctrl) ten times it; the result is rounded to the digits of the
/// rate, so there is no `5.000001`, and held to `min..=max`.
///
/// ```
/// use bevy_gooey::scrub_value;
/// assert_eq!(scrub_value(0.0, 50.0, 0.1, 0.0, 100.0, false, false), 5.0);
/// assert_eq!(scrub_value(0.0, 50.0, 0.1, 0.0, 100.0, true, false), 0.5);
/// assert_eq!(scrub_value(0.0, 50.0, 0.1, 0.0, 100.0, false, true), 50.0);
/// assert_eq!(scrub_value(0.0, 5000.0, 0.1, 0.0, 100.0, false, false), 100.0);
/// ```
pub fn scrub_value(
    start: f32,
    distance: f32,
    step: f32,
    min: f32,
    max: f32,
    fine: bool,
    coarse: bool,
) -> f32 {
    let rate = step
        * if fine {
            0.1
        } else if coarse {
            10.0
        } else {
            1.0
        };
    let raw = start + distance * rate;
    if !raw.is_finite() {
        return start;
    }
    let scale = 10f32.powi(number_decimals(rate).max(number_decimals(step)) as i32);
    hold((raw * scale).round() / scale, min, max)
}

/// A number moved by `steps` of `step` (negative goes down), rounded to the digits of the step and
/// held to `min..=max`. A key, the D-pad or an arrow press is one step; Shift is ten.
///
/// ```
/// use bevy_gooey::step_value;
/// assert_eq!(step_value(0.3, 1.0, 0.1, 0.0, 1.0), 0.4);
/// assert_eq!(step_value(0.95, 10.0, 0.1, 0.0, 1.0), 1.0);
/// ```
pub fn step_value(value: f32, steps: f32, step: f32, min: f32, max: f32) -> f32 {
    let scale = 10f32.powi(number_decimals(step) as i32);
    hold(((value + steps * step) * scale).round() / scale, min, max)
}

/// `value` held to `min..=max`, whichever order the two came in, and never a panic on a NaN.
pub(crate) fn hold(value: f32, min: f32, max: f32) -> f32 {
    value.clamp(min.min(max), max.max(min))
}

/// Why a [`crate::color_field`] would not take what the player typed; it reads as words
/// ([`std::fmt::Display`]) and is sent with [`crate::ColorRefused`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub enum HexError {
    /// Nothing was typed.
    Empty,
    /// Not 3, 4, 6 or 8 digits.
    Length,
    /// A character that is not a hex digit.
    NotHex,
}

impl std::fmt::Display for HexError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(match self {
            Self::Empty => "type a colour, like #ff8800",
            Self::Length => "a colour is 3, 4, 6 or 8 hex digits",
            Self::NotHex => "that is not a hex colour",
        })
    }
}

/// The colour a player typed as hex: `#RGB`, `#RGBA`, `#RRGGBB` or `#RRGGBBAA`, the `#` optional,
/// either case, spaces round it ignored. Returns sRGB red, green, blue and alpha, each a byte over
/// 255 (`#f80` is `#ff8800`, as in CSS and as Blender takes shorthand).
///
/// ```
/// use bevy_gooey::{HexError, parse_hex};
/// assert_eq!(parse_hex("#ff8800"), Ok([1.0, 136.0 / 255.0, 0.0, 1.0]));
/// assert_eq!(parse_hex("f80"), parse_hex("#FF8800"));
/// assert_eq!(parse_hex("#f80"), parse_hex("#ff8800ff"));
/// assert_eq!(parse_hex("#ff880"), Err(HexError::Length));
/// assert_eq!(parse_hex("orange"), Err(HexError::NotHex));
/// assert_eq!(parse_hex(" "), Err(HexError::Empty));
/// ```
pub fn parse_hex(text: &str) -> Result<[f32; 4], HexError> {
    let text = text.trim();
    let digits = text.strip_prefix('#').unwrap_or(text).trim();
    if digits.is_empty() {
        return Err(HexError::Empty);
    }
    if !digits.is_ascii() {
        return Err(HexError::NotHex);
    }
    if !matches!(digits.len(), 3 | 4 | 6 | 8) {
        return if digits.bytes().all(|b| b.is_ascii_hexdigit()) {
            Err(HexError::Length)
        } else {
            Err(HexError::NotHex)
        };
    }
    let mut bytes = [255u8; 4];
    let short = digits.len() <= 4;
    for (i, slot) in bytes
        .iter_mut()
        .take(digits.len() / if short { 1 } else { 2 })
        .enumerate()
    {
        let part = if short {
            &digits[i..=i]
        } else {
            &digits[2 * i..2 * i + 2]
        };
        let n = u8::from_str_radix(part, 16).map_err(|_| HexError::NotHex)?;
        *slot = if short { n * 17 } else { n };
    }
    Ok(bytes.map(|b| f32::from(b) / 255.0))
}

/// A colour as the hex a field shows: `#RRGGBB` in capitals, with `AA` after it only when the alpha
/// is not full, so the text says no more than the colour. `rgba` is sRGB, each channel 0 to 1.
///
/// ```
/// assert_eq!(bevy_gooey::hex_text([1.0, 136.0 / 255.0, 0.0, 1.0]), "#FF8800");
/// assert_eq!(bevy_gooey::hex_text([0.0, 0.0, 0.0, 0.5]), "#00000080");
/// ```
pub fn hex_text(rgba: [f32; 4]) -> String {
    let byte = |c: f32| (c.clamp(0.0, 1.0) * 255.0).round() as u8;
    let [r, g, b, a] = rgba.map(byte);
    if a == 255 {
        format!("#{r:02X}{g:02X}{b:02X}")
    } else {
        format!("#{r:02X}{g:02X}{b:02X}{a:02X}")
    }
}

/// A hue in degrees (any number: 360 is 0), a saturation and a value (each held to 0 to 1) as sRGB
/// red, green and blue.
///
/// ```
/// assert_eq!(bevy_gooey::hsv_to_rgb(0.0, 1.0, 1.0), [1.0, 0.0, 0.0]);
/// assert_eq!(bevy_gooey::hsv_to_rgb(360.0, 1.0, 1.0), [1.0, 0.0, 0.0]);
/// assert_eq!(bevy_gooey::hsv_to_rgb(120.0, 0.0, 0.5), [0.5, 0.5, 0.5]);
/// ```
pub fn hsv_to_rgb(hue: f32, saturation: f32, value: f32) -> [f32; 3] {
    let h = if hue.is_finite() {
        hue.rem_euclid(360.0) / 60.0
    } else {
        0.0
    };
    let s = saturation.clamp(0.0, 1.0);
    let v = value.clamp(0.0, 1.0);
    let chroma = v * s;
    let x = chroma * (1.0 - (h % 2.0 - 1.0).abs());
    let m = v - chroma;
    let (r, g, b) = match h as u8 {
        0 => (chroma, x, 0.0),
        1 => (x, chroma, 0.0),
        2 => (0.0, chroma, x),
        3 => (0.0, x, chroma),
        4 => (x, 0.0, chroma),
        _ => (chroma, 0.0, x),
    };
    [r + m, g + m, b + m]
}

/// The hue (degrees, 0 up to 360), saturation and value of an sRGB colour. A grey has no hue and a
/// black has no saturation either, so those come back as they were in `previous`
/// (`[hue, saturation, value]`): dragging a picker to black and back, or typing a grey, does not
/// forget the hue the player was on.
///
/// ```
/// use bevy_gooey::rgb_to_hsv;
/// assert_eq!(rgb_to_hsv([0.0, 1.0, 0.0], [0.0; 3]), [120.0, 1.0, 1.0]);
/// // A grey keeps the hue it was given.
/// assert_eq!(rgb_to_hsv([0.5, 0.5, 0.5], [200.0, 0.4, 0.9]), [200.0, 0.0, 0.5]);
/// // Black keeps the hue and the saturation.
/// assert_eq!(rgb_to_hsv([0.0, 0.0, 0.0], [200.0, 0.4, 0.9]), [200.0, 0.4, 0.0]);
/// ```
pub fn rgb_to_hsv(rgb: [f32; 3], previous: [f32; 3]) -> [f32; 3] {
    const EPSILON: f32 = 1e-6;
    let [r, g, b] = rgb;
    let max = r.max(g).max(b);
    let delta = max - r.min(g).min(b);
    if max <= EPSILON {
        return [previous[0], previous[1], 0.0];
    }
    if delta <= EPSILON {
        return [previous[0], 0.0, max];
    }
    let hue = if max == r {
        ((g - b) / delta).rem_euclid(6.0)
    } else if max == g {
        (b - r) / delta + 2.0
    } else {
        (r - g) / delta + 4.0
    };
    [hue * 60.0, delta / max, max]
}

/// The saturation and value a pointer at `offset` (px from the area's top-left corner) means in a
/// colour area whose frame leaves the inside `inner_size` at `inner_origin`: saturation grows to
/// the right, value upwards, both held to 0 to 1 so a drag that leaves the area holds at its edge.
/// A frame with no inside reads as the middle.
///
/// ```
/// use bevy_gooey::area_values;
/// assert_eq!(area_values([100.0, 0.0], [0.0, 0.0], [100.0, 50.0]), [1.0, 1.0]);
/// assert_eq!(area_values([0.0, 50.0], [0.0, 0.0], [100.0, 50.0]), [0.0, 0.0]);
/// assert_eq!(area_values([-30.0, 25.0], [0.0, 0.0], [100.0, 50.0]), [0.0, 0.5]);
/// ```
pub fn area_values(offset: [f32; 2], inner_origin: [f32; 2], inner_size: [f32; 2]) -> [f32; 2] {
    let along = |p: f32, origin: f32, size: f32| {
        if size > 0.0 && p.is_finite() {
            ((p - origin) / size).clamp(0.0, 1.0)
        } else {
            0.5
        }
    };
    [
        along(offset[0], inner_origin[0], inner_size[0]),
        1.0 - along(offset[1], inner_origin[1], inner_size[1]),
    ]
}

/// One turn of a [`spinner`](crate::spinner), in seconds.
pub const SPINNER_PERIOD_SECS: f32 = 0.9;

/// How far a spinner has turned `elapsed` seconds into real time, radians in `0..TAU`. A pure
/// function of the clock, so a stalled frame does not slow it and a pause does not stop it.
///
/// ```
/// let quarter = bevy_gooey::model::SPINNER_PERIOD_SECS / 4.0;
/// assert!((bevy_gooey::model::spinner_angle(quarter) - std::f32::consts::FRAC_PI_2).abs() < 1e-5);
/// ```
pub fn spinner_angle(elapsed: f32) -> f32 {
    if !elapsed.is_finite() {
        return 0.0;
    }
    let turns = (elapsed / SPINNER_PERIOD_SECS).rem_euclid(1.0);
    turns * std::f32::consts::TAU
}

/// From this many seconds left a cooldown is read in whole seconds; under it, in tenths.
pub const COOLDOWN_WHOLE_SECONDS_FROM: f32 = 3.0;

/// Float noise (0.3 * 10 is 3.0000001) must not push a round number up a step.
const COOLDOWN_ROUND_SLACK: f32 = 1e-3;

/// The words on a cooldown's chip for `remaining` seconds: `m:ss` from a minute, whole seconds
/// rounded up from [`COOLDOWN_WHOLE_SECONDS_FROM`], tenths rounded up below it, so a second that
/// is not over does not read as the next one down and the last tenth is "0.1", never "0.0".
/// Empty at zero, below it, or when not finite (a ready widget draws no chip).
///
/// ```
/// use bevy_gooey::model::cooldown_text;
/// assert_eq!(cooldown_text(65.2), "1:06");
/// assert_eq!(cooldown_text(12.0), "12");
/// assert_eq!(cooldown_text(5.01), "6");
/// assert_eq!(cooldown_text(2.31), "2.4");
/// assert_eq!(cooldown_text(0.0), "");
/// ```
pub fn cooldown_text(remaining: f32) -> String {
    if !remaining.is_finite() || remaining <= 0.0 {
        return String::new();
    }
    if remaining < COOLDOWN_WHOLE_SECONDS_FROM {
        let tenths = ((remaining * 10.0 - COOLDOWN_ROUND_SLACK).ceil() as u32).max(1);
        return format!("{}.{}", tenths / 10, tenths % 10);
    }
    let seconds = (remaining - COOLDOWN_ROUND_SLACK).ceil() as u32;
    if seconds >= 60 {
        format!("{}:{:02}", seconds / 60, seconds % 60)
    } else {
        seconds.to_string()
    }
}

/// The same time as a screen reader should say it: "1 second remaining", "6 seconds remaining",
/// "1 minute 5 seconds remaining". Empty when `remaining` is zero, below it or not finite.
///
/// ```
/// use bevy_gooey::model::cooldown_words;
/// assert_eq!(cooldown_words(5.01), "6 seconds remaining");
/// assert_eq!(cooldown_words(0.4), "1 second remaining");
/// assert_eq!(cooldown_words(65.0), "1 minute 5 seconds remaining");
/// ```
pub fn cooldown_words(remaining: f32) -> String {
    if !remaining.is_finite() || remaining <= 0.0 {
        return String::new();
    }
    let seconds = ((remaining - COOLDOWN_ROUND_SLACK).ceil() as u32).max(1);
    let (minutes, rest) = (seconds / 60, seconds % 60);
    let plural = |n: u32, unit: &str| format!("{n} {unit}{}", if n == 1 { "" } else { "s" });
    match (minutes, rest) {
        (0, s) => format!("{} remaining", plural(s, "second")),
        (m, 0) => format!("{} remaining", plural(m, "minute")),
        (m, s) => format!("{} {} remaining", plural(m, "minute"), plural(s, "second")),
    }
}

/// The angle, clockwise from twelve o'clock, that a cooldown's clear wedge has opened to: `0` the
/// moment it starts (all dimmed) to `TAU` when `remaining` reaches zero. A duration that is not
/// positive or not finite counts as fully dimmed while any time remains, and `remaining` outside
/// `0..=duration` is held to the nearest end.
///
/// ```
/// use bevy_gooey::model::cooldown_sweep;
/// assert!((cooldown_sweep(6.0, 8.0) - std::f32::consts::FRAC_PI_2).abs() < 1e-5);
/// assert_eq!(cooldown_sweep(8.0, 8.0), 0.0);
/// ```
pub fn cooldown_sweep(remaining: f32, duration: f32) -> f32 {
    if !remaining.is_finite() || remaining <= 0.0 {
        return std::f32::consts::TAU;
    }
    if !duration.is_finite() || duration <= 0.0 {
        return 0.0;
    }
    (1.0 - (remaining / duration).clamp(0.0, 1.0)) * std::f32::consts::TAU
}

/// How many times faster a hold's bar unwinds than it filled: committing is deliberate, backing out
/// is free. A design default (`docs/research/hold-button.md`).
pub const HOLD_UNWIND_RATE: f32 = 4.0;
/// The most a hold's duration is stretched by the player's setting, a factor on the game's seconds.
pub const HOLD_SCALE_MAX: f32 = 4.0;

/// The seconds a hold takes: the game's `seconds` times the player's `scale` (held to `0.0` to
/// [`HOLD_SCALE_MAX`], NaN read as `1.0`). Zero, or a `seconds` that is not a positive finite
/// number, is a tap: the hold is replaced by a press that confirms when it is let go.
///
/// ```
/// use bevy_gooey::model::hold_seconds;
/// assert_eq!(hold_seconds(1.2, 1.0), 1.2);
/// assert_eq!(hold_seconds(1.2, 0.5), 0.6);
/// assert_eq!(hold_seconds(1.2, 0.0), 0.0);
/// assert_eq!(hold_seconds(f32::NAN, 1.0), 0.0);
/// ```
pub fn hold_seconds(seconds: f32, scale: f32) -> f32 {
    if !seconds.is_finite() || seconds <= 0.0 {
        return 0.0;
    }
    let scale = if scale.is_nan() {
        1.0
    } else {
        scale.clamp(0.0, HOLD_SCALE_MAX)
    };
    seconds * scale
}

/// A hold's progress, `0.0` to `1.0`, after `dt` seconds. Held, it rises by `dt / seconds` (a tap,
/// `seconds` of zero, is full at once); let go, it unwinds [`HOLD_UNWIND_RATE`] times as fast as it
/// rose, never taking more than half a second to empty, or at once when `instant` (the player's
/// motion is off).
///
/// ```
/// use bevy_gooey::model::hold_step;
/// assert_eq!(hold_step(0.0, 0.3, 1.2, true, false), 0.25);
/// assert_eq!(hold_step(0.5, 0.1, 1.2, true, false), 0.5 + 0.1 / 1.2);
/// assert_eq!(hold_step(0.5, 10.0, 1.2, false, false), 0.0);
/// assert_eq!(hold_step(0.5, 0.01, 1.2, false, true), 0.0);
/// assert_eq!(hold_step(0.0, 0.0, 0.0, true, false), 1.0);
/// ```
pub fn hold_step(progress: f32, dt: f32, seconds: f32, held: bool, instant: bool) -> f32 {
    let progress = if progress.is_finite() {
        progress.clamp(0.0, 1.0)
    } else {
        0.0
    };
    let dt = if dt.is_finite() { dt.max(0.0) } else { 0.0 };
    if held {
        if seconds <= 0.0 {
            return 1.0;
        }
        return (progress + dt / seconds).min(1.0);
    }
    if instant {
        return 0.0;
    }
    let unwind = seconds.clamp(0.4, 2.0) / HOLD_UNWIND_RATE;
    (progress - dt / unwind).max(0.0)
}

/// How far a dialog's card rises into place, logical px.
pub const DIALOG_SLIDE_PX: f32 = 12.0;
/// How far a popover (a menu, a select list, a colour picker) slides from its anchor, logical px.
pub const POPOVER_SLIDE_PX: f32 = 6.0;

/// The least a spring's position may be off its target, logical px, for it to count as at rest:
/// below the 1/64 px a layout snaps to, so the last snap is invisible. Rune's `PropClass::eps` for
/// spatial values.
pub const SPRING_REST_POSITION: f32 = 1.0 / 128.0;
/// The most a spring's speed may be, logical px a second, for it to count as at rest: ten times
/// [`SPRING_REST_POSITION`] a second.
pub const SPRING_REST_SPEED: f32 = SPRING_REST_POSITION * 10.0;
/// The longest [`spring_settle_seconds`] will answer, seconds: a spring that has not settled by then
/// is not one a person is waiting for.
pub const SPRING_MAX_SETTLE_SECONDS: f32 = 120.0;
/// How near ζ = 1 a spring is taken as critically damped, where the under- and over-damped closed
/// forms divide by something near zero.
const SPRING_CRITICAL_BAND: f64 = 1e-4;

/// A spring in the terms a person tunes it by, SwiftUI's `Spring(duration:bounce:)` (mass 1).
///
/// `duration` is the *perceptual* duration in seconds, the period of the undamped spring
/// (`ω = 2π / duration`), not the time it takes to settle, which is longer and depends on the
/// bounce ([`spring_settle_seconds`]). `bounce` is in the open range −1 to 1: 0 is critically
/// damped (the general-purpose spring: it arrives and stops), above 0 overshoots (`ζ = 1 − bounce`),
/// below 0 is flattened, a longer and flatter tail (`ζ = 1 / (1 + bounce)`). Build one with
/// [`Spring::new`], which refuses a value that has no motion; a spring read from data may still be
/// bad, which [`Spring::is_valid`] says and [`crate::GooeySkin::problems`] reports.
///
/// ```
/// use bevy_gooey::model::{Spring, SpringState, spring_step};
/// let spring = Spring::new(0.3, 0.0).unwrap();
/// let mut state = SpringState { value: 0.0, velocity: 0.0 };
/// for _ in 0..60 {
///     state = spring_step(spring, state, 100.0, 1.0 / 60.0);
/// }
/// assert!((state.value - 100.0).abs() < 0.01);
/// assert!(Spring::new(0.0, 0.0).is_err());
/// ```
#[derive(Clone, Copy, Debug, PartialEq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
pub struct Spring {
    /// The perceptual duration, seconds: above zero and finite.
    pub duration: f32,
    /// How much it overshoots: above −1 and below 1.
    pub bounce: f32,
}

/// Why a [`Spring`] could not be made.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum SpringError {
    /// The duration was not finite or not above zero.
    Duration(f32),
    /// The bounce was not in the open range −1 to 1.
    Bounce(f32),
}

impl std::fmt::Display for SpringError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Duration(d) => write!(f, "a spring's duration must be above zero, not {d}"),
            Self::Bounce(b) => write!(f, "a spring's bounce must be between -1 and 1, not {b}"),
        }
    }
}

impl std::error::Error for SpringError {}

impl Spring {
    /// A spring of `duration` seconds and `bounce`, or the reason it has none: a duration that is
    /// not above zero (or not finite), or a bounce outside −1 to 1 (or not a number).
    pub fn new(duration: f32, bounce: f32) -> Result<Self, SpringError> {
        let spring = Self { duration, bounce };
        if !(duration.is_finite() && duration > 0.0) {
            Err(SpringError::Duration(duration))
        } else if !(bounce > -1.0 && bounce < 1.0) {
            Err(SpringError::Bounce(bounce))
        } else {
            Ok(spring)
        }
    }

    /// Whether the spring is one [`Spring::new`] would have made.
    pub fn is_valid(&self) -> bool {
        Self::new(self.duration, self.bounce).is_ok()
    }

    /// The same spring with every length multiplied by `scale` (the player's
    /// [`crate::MotionSettings::duration_scale`]). A scale that is not above zero or not finite
    /// gives the spring back unchanged: whether to move at all is the caller's question.
    pub fn scaled(self, scale: f32) -> Self {
        if scale.is_finite() && scale > 0.0 {
            Self {
                duration: self.duration * scale,
                ..self
            }
        } else {
            self
        }
    }

    /// The undamped angular frequency, radians a second.
    fn omega(&self) -> f64 {
        std::f64::consts::TAU / f64::from(self.duration)
    }

    /// The damping ratio.
    fn zeta(&self) -> f64 {
        let bounce = f64::from(self.bounce);
        if bounce >= 0.0 {
            1.0 - bounce
        } else {
            1.0 / (1.0 + bounce)
        }
    }
}

/// Where a [`Spring`] is and how fast it is going.
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct SpringState {
    /// The value now.
    pub value: f32,
    /// Its speed now, value units a second.
    pub velocity: f32,
}

/// The closed form of a spring a time `t` after it left an offset `a` from its target at speed
/// `v0`: `(offset, velocity)`. Exact for any `t`, so a step of `a + b` equals a step of `a` then
/// one of `b`, and a retarget is a new call from the state it ended in.
fn spring_solution(spring: &Spring, a: f64, v0: f64, t: f64) -> (f64, f64) {
    let omega = spring.omega();
    let zeta = spring.zeta();
    if (zeta - 1.0).abs() < SPRING_CRITICAL_BAND {
        // (a + b t) e^{-ωt}
        let b = v0 + omega * a;
        let decay = (-omega * t).exp();
        ((a + b * t) * decay, (v0 - omega * b * t) * decay)
    } else if zeta < 1.0 {
        // e^{-σt} (a cos ω_d t + B sin ω_d t)
        let sigma = zeta * omega;
        let damped = omega * (1.0 - zeta * zeta).sqrt();
        let b = (v0 + sigma * a) / damped;
        let decay = (-sigma * t).exp();
        let (sin, cos) = (damped * t).sin_cos();
        (
            decay * (a * cos + b * sin),
            decay * (v0 * cos - (sigma * b + a * damped) * sin),
        )
    } else {
        // c1 e^{r1 t} + c2 e^{r2 t}
        let root = (zeta * zeta - 1.0).sqrt();
        let r1 = -omega * (zeta - root);
        let r2 = -omega * (zeta + root);
        let c1 = (v0 - r2 * a) / (r1 - r2);
        let c2 = a - c1;
        let (e1, e2) = ((r1 * t).exp(), (r2 * t).exp());
        (c1 * e1 + c2 * e2, c1 * r1 * e1 + c2 * r2 * e2)
    }
}

/// A [`Spring`]'s state `dt` seconds on, moving toward `target`. Closed form: exact at any `dt`, the
/// same at 60 Hz and at 120 Hz, and a new `target` simply continues from the state with its
/// velocity (value and speed stay continuous). A `dt` of zero (or below) gives the state back, and
/// so does one that is not finite, a target that is not, or a spring that is not
/// [`Spring::is_valid`]: the caller, which knows where it is, says so.
///
/// ```
/// use bevy_gooey::model::{Spring, SpringState, spring_step};
/// let spring = Spring::new(0.3, 0.0).unwrap();
/// let at = SpringState { value: 4.0, velocity: 2.0 };
/// assert_eq!(spring_step(spring, at, 10.0, 0.0), at);
/// assert_eq!(spring_step(spring, at, f32::NAN, 0.1), at);
/// ```
pub fn spring_step(spring: Spring, state: SpringState, target: f32, dt: f32) -> SpringState {
    if !(dt.is_finite() && dt > 0.0)
        || !target.is_finite()
        || !state.value.is_finite()
        || !state.velocity.is_finite()
        || !spring.is_valid()
    {
        return state;
    }
    let a = f64::from(state.value) - f64::from(target);
    let (offset, velocity) = spring_solution(&spring, a, f64::from(state.velocity), f64::from(dt));
    SpringState {
        value: (f64::from(target) + offset) as f32,
        velocity: velocity as f32,
    }
}

/// Whether a spring at `state` is at rest on `target`: within [`SPRING_REST_POSITION`] of it and
/// going no faster than [`SPRING_REST_SPEED`]. The place to snap to the target and stop writing.
pub fn spring_at_rest(state: SpringState, target: f32) -> bool {
    (state.value - target).abs() <= SPRING_REST_POSITION
        && state.velocity.abs() <= SPRING_REST_SPEED
}

/// Whether `state` has settled on `target` *for this spring*, to `tolerance` in the value's own unit
/// (a pixel, a scale, a fraction of a bar): within `tolerance` of it and going so slowly that it
/// would move less than `tolerance` in the time it takes to turn (`1 / ω`). Unlike
/// [`spring_at_rest`], whose speed limit is absolute, this is the same for a spring stretched to twice
/// its length, so the player's [`crate::MotionSettings::duration_scale`] doubles the time to settle
/// and no more. Every motion the crate draws settles by this rule.
pub fn spring_settled(spring: Spring, state: SpringState, target: f32, tolerance: f32) -> bool {
    spring.is_valid()
        && (state.value - target).abs() <= tolerance
        && f64::from(state.velocity.abs()) <= f64::from(tolerance) * spring.omega()
}

/// How long a spring takes, from `state`, to come to rest on `target` and stay there
/// ([`spring_at_rest`]): the time its decaying envelope needs, so a little over the time it is
/// actually first at rest. 0 when it already is, [`SPRING_MAX_SETTLE_SECONDS`] when it does not
/// settle (or an input is not finite). A 0.3 s spring with no bounce, from 0 to 100, takes about
/// 0.6 s.
///
/// ```
/// use bevy_gooey::model::{Spring, SpringState, spring_settle_seconds};
/// let spring = Spring::new(0.3, 0.0).unwrap();
/// let from = SpringState { value: 0.0, velocity: 0.0 };
/// let seconds = spring_settle_seconds(spring, from, 100.0);
/// assert!(seconds > 0.3 && seconds < 1.0, "{seconds}");
/// ```
pub fn spring_settle_seconds(spring: Spring, state: SpringState, target: f32) -> f32 {
    if !spring.is_valid()
        || !target.is_finite()
        || !state.value.is_finite()
        || !state.velocity.is_finite()
    {
        return SPRING_MAX_SETTLE_SECONDS;
    }
    if spring_at_rest(state, target) {
        return 0.0;
    }
    let max = f64::from(SPRING_MAX_SETTLE_SECONDS);
    let omega = spring.omega();
    let zeta = spring.zeta();
    let a = f64::from(state.value) - f64::from(target);
    let v0 = f64::from(state.velocity);
    let (rest_position, rest_speed) = (
        f64::from(SPRING_REST_POSITION),
        f64::from(SPRING_REST_SPEED),
    );
    let seconds = if (zeta - 1.0).abs() < SPRING_CRITICAL_BAND {
        let b = v0 + omega * a;
        let envelope = |t: f64| {
            let decay = (-omega * t).exp();
            (
                (a.abs() + b.abs() * t) * decay,
                (v0.abs() + omega * b.abs() * t) * decay,
            )
        };
        bisect_after(1.0 / omega, max, |t| {
            let (p, v) = envelope(t);
            p <= rest_position && v <= rest_speed
        })
    } else if zeta < 1.0 {
        let sigma = zeta * omega;
        let damped = omega * (1.0 - zeta * zeta).sqrt();
        let b = (v0 + sigma * a) / damped;
        let position = a.hypot(b);
        let speed = v0.hypot(sigma * b + a * damped);
        ((position / rest_position)
            .ln()
            .max((speed / rest_speed).ln())
            / sigma)
            .max(0.0)
    } else {
        let root = (zeta * zeta - 1.0).sqrt();
        let r1 = -omega * (zeta - root);
        let r2 = -omega * (zeta + root);
        let c1 = (v0 - r2 * a) / (r1 - r2);
        let c2 = a - c1;
        bisect_after(0.0, max, |t| {
            let (e1, e2) = ((r1 * t).exp(), (r2 * t).exp());
            c1.abs() * e1 + c2.abs() * e2 <= rest_position
                && (c1 * r1).abs() * e1 + (c2 * r2).abs() * e2 <= rest_speed
        })
    };
    if seconds.is_finite() {
        seconds.clamp(0.0, max) as f32
    } else {
        SPRING_MAX_SETTLE_SECONDS
    }
}

/// The smallest `t` in `from..=max` where `ok` holds, for a predicate that stays true once true
/// (`max` when it never does).
fn bisect_after(from: f64, max: f64, ok: impl Fn(f64) -> bool) -> f64 {
    if ok(from) {
        return from;
    }
    if !ok(max) {
        return max;
    }
    let (mut lo, mut hi) = (from, max);
    for _ in 0..60 {
        let mid = 0.5 * (lo + hi);
        if ok(mid) {
            hi = mid;
        } else {
            lo = mid;
        }
    }
    hi
}

/// How long is left, in words: "about 20 s left", "about 3 min left", "about 1 h 5 min left". Under
/// ten seconds it counts the seconds, to a minute it rounds to five, to an hour to the minute and
/// past one to five minutes, because an estimate never has the precision it prints. A time that is
/// not finite or below zero is empty; under a second it says so.
///
/// ```
/// assert_eq!(bevy_gooey::model::eta_words(20.0), "about 20 s left");
/// assert_eq!(bevy_gooey::model::eta_words(3900.0), "about 1 h 5 min left");
/// ```
pub fn eta_words(seconds: f32) -> String {
    if !seconds.is_finite() || seconds < 0.0 {
        return String::new();
    }
    if seconds < 1.0 {
        return "less than a second left".to_string();
    }
    let whole = seconds.round() as u64;
    if whole < 10 {
        return format!("about {whole} s left");
    }
    if whole < 58 {
        return format!("about {} s left", (whole + 2) / 5 * 5);
    }
    if whole < 3600 {
        let minutes = (whole + 30) / 60;
        if minutes < 60 {
            return format!("about {minutes} min left");
        }
    }
    // From an hour: whole hours and the minutes to the nearest five.
    let total = (whole + 150) / 300 * 5;
    let (hours, minutes) = (total / 60, total % 60);
    if minutes == 0 {
        format!("about {hours} h left")
    } else {
        format!("about {hours} h {minutes} min left")
    }
}

/// The line under a progress bar: "3 of 7: Measuring meshes, about 20 s left". Either part may be
/// missing, and with neither the line is empty.
///
/// ```
/// use bevy_gooey::model::progress_text;
/// assert_eq!(
///     progress_text(Some((3, 7, "Measuring meshes")), Some(20.0)),
///     "3 of 7: Measuring meshes, about 20 s left"
/// );
/// assert_eq!(progress_text(None, Some(4.0)), "about 4 s left");
/// ```
pub fn progress_text(step: Option<(u32, u32, &str)>, eta_seconds: Option<f32>) -> String {
    let step = step.map(|(at, of, name)| {
        if name.is_empty() {
            format!("{at} of {of}")
        } else {
            format!("{at} of {of}: {name}")
        }
    });
    let left = eta_seconds.map(eta_words).filter(|words| !words.is_empty());
    match (step, left) {
        (Some(step), Some(left)) => format!("{step}, {left}"),
        (Some(only), None) | (None, Some(only)) => only,
        (None, None) => String::new(),
    }
}

/// Which items of a bar stay when its room is short: `true` for each of `widths` that is shown.
///
/// Everything shows when it fits `room` (items `gap` apart). Otherwise `reserve` (the room a "More"
/// button takes, its gap included, `0.0` for a bar with none) is kept free and items hide **lowest
/// rank first, the later of equal ranks first**, until the rest fit. Hidden items take no room and
/// no gap; non-finite or negative widths count as nothing.
///
/// ```
/// use bevy_gooey::model::bar_fit;
/// // Three 100 px items, 8 px apart: 316 px. In 300 px the last one hides.
/// assert_eq!(bar_fit(&[100.0; 3], &[0; 3], 8.0, 300.0, 0.0), [true, true, false]);
/// // The lowest rank goes first, wherever it stands.
/// assert_eq!(bar_fit(&[100.0; 3], &[5, 1, 5], 8.0, 300.0, 0.0), [true, false, true]);
/// ```
pub fn bar_fit(widths: &[f32], ranks: &[u32], gap: f32, room: f32, reserve: f32) -> Vec<bool> {
    let width = |w: f32| if w.is_finite() { w.max(0.0) } else { 0.0 };
    let needed = |shown: &[bool]| {
        let (sum, count) = widths
            .iter()
            .zip(shown)
            .filter(|(_, shown)| **shown)
            .fold((0.0, 0usize), |(sum, count), (w, _)| {
                (sum + width(*w), count + 1)
            });
        sum + gap * count.saturating_sub(1) as f32
    };
    let mut shown = vec![true; widths.len()];
    if needed(&shown) <= room {
        return shown;
    }
    let room = room - reserve;
    while needed(&shown) > room {
        let next = (0..widths.len())
            .filter(|&i| shown[i])
            .min_by_key(|&i| (ranks.get(i).copied().unwrap_or(0), std::cmp::Reverse(i)));
        match next {
            Some(i) => shown[i] = false,
            None => break,
        }
    }
    shown
}

/// A direction on the screen, `y` growing down, in which a carried payload's mark moves.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Toward {
    /// Towards the top of the screen.
    Up,
    /// Towards the bottom.
    Down,
    /// Towards the left.
    Left,
    /// Towards the right.
    Right,
}

/// The least distance along a direction, in logical pixels, for a target to lie "that way".
const TOWARD_EPSILON: f32 = 0.5;

/// Which of `rects` (`[x0, y0, x1, y1]`, `y` down) a payload carried by key moves to from `from`
/// when the player presses `toward`: the nearest whose centre lies strictly that way. The score is
/// the distance along the direction plus twice the distance across it, the usual weight of spatial
/// navigation, so a target straight ahead beats a nearer one far to the side; the lowest wins and a
/// tie goes to the lower index. `None` when nothing lies that way (the mark stays where it is).
///
/// ```
/// use bevy_gooey::{Toward, target_toward};
/// let from = [0., 0., 10., 10.];
/// let rects = [[20., 0., 30., 10.], [20., 40., 30., 50.], [-30., 0., -20., 10.]];
/// assert_eq!(target_toward(from, &rects, Toward::Right), Some(0));
/// assert_eq!(target_toward(from, &rects, Toward::Left), Some(2));
/// assert_eq!(target_toward(from, &rects, Toward::Up), None);
/// ```
pub fn target_toward(from: [f32; 4], rects: &[[f32; 4]], toward: Toward) -> Option<usize> {
    let centre = |r: &[f32; 4]| [(r[0] + r[2]) / 2.0, (r[1] + r[3]) / 2.0];
    let origin = centre(&from);
    let mut best: Option<(usize, f32)> = None;
    for (index, rect) in rects.iter().enumerate() {
        let at = centre(rect);
        let (dx, dy) = (at[0] - origin[0], at[1] - origin[1]);
        let (along, across) = match toward {
            Toward::Right => (dx, dy.abs()),
            Toward::Left => (-dx, dy.abs()),
            Toward::Down => (dy, dx.abs()),
            Toward::Up => (-dy, dx.abs()),
        };
        if along.is_nan() || along <= TOWARD_EPSILON || !across.is_finite() {
            continue;
        }
        let score = along + 2.0 * across;
        if best.is_none_or(|(_, lowest)| score < lowest) {
            best = Some((index, score));
        }
    }
    best.map(|(index, _)| index)
}

/// The next (or previous) of `rects` in reading order (top to bottom by the top edge, left to right
/// by the left edge, ties by index), wrapping at the ends: the step of a payload carried by key
/// that is not a direction (PageDown, a bumper). With no `current` the first is next and the last
/// is previous. `None` only when there are no rects.
///
/// ```
/// use bevy_gooey::target_step;
/// let rects = [[0., 50., 10., 60.], [0., 0., 10., 10.], [20., 0., 30., 10.]];
/// assert_eq!(target_step(&rects, None, true), Some(1));
/// assert_eq!(target_step(&rects, Some(1), true), Some(2));
/// assert_eq!(target_step(&rects, Some(0), true), Some(1));
/// ```
pub fn target_step(rects: &[[f32; 4]], current: Option<usize>, forward: bool) -> Option<usize> {
    let mut order: Vec<usize> = (0..rects.len()).collect();
    order.sort_by(|&a, &b| {
        rects[a][1]
            .total_cmp(&rects[b][1])
            .then(rects[a][0].total_cmp(&rects[b][0]))
            .then(a.cmp(&b))
    });
    let last = order.len().checked_sub(1)?;
    let at = current.and_then(|c| order.iter().position(|&i| i == c));
    let next = match (at, forward) {
        (None, true) => 0,
        (None, false) => last,
        (Some(at), true) => (at + 1) % order.len(),
        (Some(at), false) => (at + last) % order.len(),
    };
    Some(order[next])
}

/// Whether the box `[min, max]` lies wholly outside the rectangle `[view_min, view_max]`: no
/// overlap at all, so nothing of it would be drawn. Touching edges count as inside.
///
/// ```
/// use bevy_gooey::box_outside;
/// assert!(box_outside((1300.0, 10.0), (1340.0, 40.0), (0.0, 0.0), (1280.0, 720.0)));
/// assert!(!box_outside((1270.0, 10.0), (1310.0, 40.0), (0.0, 0.0), (1280.0, 720.0)));
/// ```
pub fn box_outside(
    min: (f32, f32),
    max: (f32, f32),
    view_min: (f32, f32),
    view_max: (f32, f32),
) -> bool {
    max.0 < view_min.0 || min.0 > view_max.0 || max.1 < view_min.1 || min.1 > view_max.1
}

/// Where a point outside the rectangle `[min, max]` is pinned to its edge: on the ray from
/// `centre` toward `point`, so the pinned position still says which way the point lies. A point
/// inside is returned as it is. The result is never outside the rectangle (an empty one, `min`
/// past `max`, gives `centre`).
///
/// ```
/// use bevy_gooey::pin_to_edge;
/// // Far to the right of a 1280 x 720 viewport, level with its middle: on the right edge.
/// assert_eq!(pin_to_edge((5000.0, 360.0), (640.0, 360.0), (64.0, 36.0), (1216.0, 684.0)), (1216.0, 360.0));
/// // Inside: unchanged.
/// assert_eq!(pin_to_edge((100.0, 100.0), (640.0, 360.0), (64.0, 36.0), (1216.0, 684.0)), (100.0, 100.0));
/// ```
pub fn pin_to_edge(
    point: (f32, f32),
    centre: (f32, f32),
    min: (f32, f32),
    max: (f32, f32),
) -> (f32, f32) {
    if min.0 > max.0 || min.1 > max.1 || !point.0.is_finite() || !point.1.is_finite() {
        return centre;
    }
    if point.0 >= min.0 && point.0 <= max.0 && point.1 >= min.1 && point.1 <= max.1 {
        return point;
    }
    let (dx, dy) = (point.0 - centre.0, point.1 - centre.1);
    let reach = |d: f32, from: f32, lo: f32, hi: f32| {
        if d > 0.0 {
            (hi - from) / d
        } else if d < 0.0 {
            (lo - from) / d
        } else {
            f32::INFINITY
        }
    };
    let s = reach(dx, centre.0, min.0, max.0).min(reach(dy, centre.1, min.1, max.1));
    let s = if s.is_finite() { s.max(0.0) } else { 0.0 };
    (
        (centre.0 + dx * s).clamp(min.0, max.0),
        (centre.1 + dy * s).clamp(min.1, max.1),
    )
}

