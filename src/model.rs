//! The engine-free maths under the skin: contrast, compositing, meter fill, the interface's scale
//! against the window and line weights on whole device pixels.
//!
//! Plain functions over `[r, g, b]` arrays in sRGB and plain sizes, testable without an app.
//! [`crate::GooeySkin::problems`] is built on them, and a host or an editor may call them to check
//! its own colours; [`crate::scale_with_window`] on [`window_ui_scale`]; [`crate::apply_skin`] on
//! [`snap_line_width`].

/// The least contrast body text may have against its background: WCAG 2.2, success criterion 1.4.3.
pub const TEXT_CONTRAST: f32 = 4.5;

/// The least contrast a focus indicator or another part of a control may have against what is next
/// to it: WCAG 2.2, success criteria 1.4.11 and 2.4.13.
pub const NON_TEXT_CONTRAST: f32 = 3.0;

/// The contrast a high-contrast mode holds every part of the interface to, against what it is drawn
/// on: WCAG 2.2 success criterion 1.4.6 (Level AAA), and Xbox Accessibility Guideline 102's "7:1 for
/// all UI elements". See [`crate::GooeySkin::high_contrast`].
pub const ENHANCED_CONTRAST: f32 = 7.0;

/// The smallest a pointer target may be, in logical pixels: WCAG 2.2, success criterion 2.5.8.
pub const MIN_TARGET_PX: f32 = 24.0;

/// The default [`crate::GooeySkin::min_target`], in logical pixels: a target a thumb or a pad's
/// focus jump lands on comfortably (WCAG 2.2, success criterion 2.5.5, is 44 px).
pub const COMFORT_TARGET_PX: f32 = 44.0;

/// The WCAG relative luminance of an sRGB colour, from 0 (black) to 1 (white).
///
/// ```
/// assert_eq!(bevy_gooey::relative_luminance([1.0, 1.0, 1.0]), 1.0);
/// ```
pub fn relative_luminance(srgb: [f32; 3]) -> f32 {
    let linear = srgb.map(|c| {
        if c <= 0.04045 {
            c / 12.92
        } else {
            ((c + 0.055) / 1.055).powf(2.4)
        }
    });
    0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]
}

/// The WCAG contrast ratio of two sRGB colours, from 1:1 (the same) to 21:1 (black on white).
///
/// ```
/// let ratio = bevy_gooey::contrast_ratio([0.0, 0.0, 0.0], [1.0, 1.0, 1.0]);
/// assert!((ratio - 21.0).abs() < 0.01);
/// ```
pub fn contrast_ratio(a: [f32; 3], b: [f32; 3]) -> f32 {
    let (la, lb) = (relative_luminance(a), relative_luminance(b));
    (la.max(lb) + 0.05) / (la.min(lb) + 0.05)
}

/// CSS's blur radius for a shadow per standard deviation of the Gaussian it blurs with: CSS says
/// "the resulting shadow must approximate the image that would be generated by applying to the
/// shadow a Gaussian blur with a standard deviation equal to half the blur radius" (CSS
/// Backgrounds and Borders 3, box-shadow), and Bevy 0.20's box-shadow shader
/// (`bevy_ui_render/src/box_shadow.wesl`) takes its `blur_radius` as that deviation: its
/// `gaussian(y, blur)` and `erf(x * sqrt(0.5) / blur)` are a Gaussian of `sigma = blur`.
pub const CSS_BLUR_PER_SIGMA: f32 = 2.0;

/// The standard deviation Bevy's `ShadowStyle::blur_radius` takes for a CSS blur radius of
/// `css_blur` logical px: half of it ([`CSS_BLUR_PER_SIGMA`]).
///
/// ```
/// // `box-shadow: 0 8px 24px` blurs with a deviation of 12 px.
/// assert_eq!(bevy_gooey::shadow_sigma(24.0), 12.0);
/// ```
pub fn shadow_sigma(css_blur: f32) -> f32 {
    css_blur / CSS_BLUR_PER_SIGMA
}

/// The least CIE L\* two adjacent surfaces of a skin's ladder may differ by: a just-noticeable
/// difference of a large flat field is about 2, and a comfortable one about 4. See
/// [`crate::GooeySkin::surfaces`].
pub const ELEVATION_STEP: f32 = 2.0;

/// The least CIE L\* a skin's pressed fill and its hovered fill may differ by, so a control with
/// the pointer down is told apart from one under it: the comfortable step (4) of
/// [`ELEVATION_STEP`]'s note, since WCAG 1.4.11 sets no number for two states that do not appear
/// side by side. See [`crate::GooeySkin::pressed`].
pub const STATE_STEP: f32 = 4.0;

/// The CIE 1976 lightness L\* of an sRGB colour, from 0 (black) to 100 (white): a perceptually
/// near-uniform scale, so equal differences look like equal steps (WCAG's contrast ratio, with its
/// flare term, is the wrong instrument between two near-blacks).
///
/// ```
/// assert_eq!(bevy_gooey::cie_lightness([0.0, 0.0, 0.0]), 0.0);
/// assert!((bevy_gooey::cie_lightness([1.0, 1.0, 1.0]) - 100.0).abs() < 0.01);
/// ```
pub fn cie_lightness(srgb: [f32; 3]) -> f32 {
    const EPSILON: f32 = 216.0 / 24389.0;
    const KAPPA: f32 = 24389.0 / 27.0;
    let y = relative_luminance(srgb);
    if y <= EPSILON {
        KAPPA * y
    } else {
        116.0 * y.cbrt() - 16.0
    }
}

/// How many points of CIE L\* a primary button's fill moves from the accent toward the text under
/// the pointer: half again [`STATE_STEP`], so the lift is seen in any skin. Pressed moves twice as
/// far. See [`crate::GooeySkin::primary_hovered`].
pub const PRIMARY_LIFT_L: f32 = 6.0;

/// How finely [`lift_toward`] walks the line between its two colours: 256 steps, finer than an
/// 8-bit channel.
const LIFT_STEPS: u16 = 256;

/// `from` moved along the straight sRGB line toward `toward` until its CIE L\* differs from
/// `from`'s by at least `step_l`, or `toward` itself when the whole line does not reach the step.
/// The first such point is taken, walking the line in 256 steps, because lightness along an sRGB line
/// need not be monotonic between two hues.
///
/// ```
/// use bevy_gooey::{cie_lightness, lift_toward};
/// let blue = [0.25, 0.5, 0.9];
/// let lifted = lift_toward(blue, [1.0; 3], 6.0);
/// let step = cie_lightness(lifted) - cie_lightness(blue);
/// assert!((6.0..6.5).contains(&step));
/// // Toward a colour of the same lightness there is no step to take: the far end.
/// assert_eq!(lift_toward(blue, blue, 6.0), blue);
/// ```
pub fn lift_toward(from: [f32; 3], toward: [f32; 3], step_l: f32) -> [f32; 3] {
    let start = cie_lightness(from);
    let at = |t: f32| {
        [
            from[0] + (toward[0] - from[0]) * t,
            from[1] + (toward[1] - from[1]) * t,
            from[2] + (toward[2] - from[2]) * t,
        ]
    };
    (1..=LIFT_STEPS)
        .map(|i| at(f32::from(i) / f32::from(LIFT_STEPS)))
        .find(|c| (cie_lightness(*c) - start).abs() >= step_l)
        .unwrap_or(toward)
}

/// `fg` at `alpha` laid over an opaque `bg`, per channel: what the eye sees of a translucent panel.
/// `alpha` is clamped to `0..=1`.
///
/// ```
/// assert_eq!(bevy_gooey::composite([1.0, 1.0, 1.0], 0.5, [0.0, 0.0, 0.0]), [0.5, 0.5, 0.5]);
/// ```
pub fn composite(fg: [f32; 3], alpha: f32, bg: [f32; 3]) -> [f32; 3] {
    let a = alpha.clamp(0.0, 1.0);
    [
        fg[0] * a + bg[0] * (1.0 - a),
        fg[1] * a + bg[1] * (1.0 - a),
        fg[2] * a + bg[2] * (1.0 - a),
    ]
}

/// How full a meter is, from 0 to 1. Never NaN: a non-finite value, a non-finite maximum or a
/// maximum at or below zero reads as empty.
///
/// ```
/// assert_eq!(bevy_gooey::meter_fraction(25.0, 100.0), 0.25);
/// ```
pub fn meter_fraction(value: f32, max: f32) -> f32 {
    if max > 0.0 && max.is_finite() && value.is_finite() {
        (value / max).clamp(0.0, 1.0)
    } else {
        0.0
    }
}

/// How long a meter's trail of lost length stands before it drains, seconds.
pub const METER_TRAIL_HOLD_SECONDS: f32 = 0.45;
/// How fast a meter's trail drains once its hold is over, in whole lengths of the bar a second.
pub const METER_TRAIL_RATE: f32 = 1.5;
/// A meter fraction this near its target is its target (under a device pixel on any bar).
pub const METER_SNAP: f32 = 0.002;

/// The fractions of its length a meter draws: the `fill` (the value) and the `trail` behind it, the
/// length that was lost, which never falls below the fill. `hold` is how long the trail still
/// stands before it drains.
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct MeterShown {
    /// The fill's fraction of the bar, `0.0..=1.0`.
    pub fill: f32,
    /// The trail's fraction, `fill..=1.0`: the fill's length before a loss, draining to the fill.
    pub trail: f32,
    /// Seconds before the trail starts to drain.
    pub hold: f32,
    /// How fast the fill is rising, bars a second: what a gain's spring carries from frame to
    /// frame. 0 at rest and after a loss.
    pub speed: f32,
    /// The target the fill was last rising to, which tells a spring that overshoots it (coming
    /// back to the same target) from a loss (a lower one). Meaningful while `speed` is not 0.
    pub aim: f32,
}

/// One step of a meter's motion: `shown` after `dt` seconds of a bar that now reads `target`
/// (`0.0..=1.0`). A loss drops the fill to the target at once and leaves a trail where it was, held
/// for [`METER_TRAIL_HOLD_SECONDS`] and then drained at [`METER_TRAIL_RATE`] (a second loss during
/// the hold does not restart it); a gain takes the fill up on `gain`, a [`Spring`] (the skin's
/// snappy one), and raises the trail with it. Every length is multiplied by `duration_scale`; at
/// zero (or any value that is not finite and above zero) the result is the target and no trail. A
/// `target` that is not finite reads as empty.
///
/// ```
/// # use bevy_gooey::{MeterShown, MotionTokens, meter_motion};
/// let gain = MotionTokens::default().snappy;
/// let full = MeterShown { fill: 1.0, trail: 1.0, hold: 0.0, speed: 0.0, aim: 1.0 };
/// let hit = meter_motion(full, 0.6, 0.016, gain, 1.0);
/// assert_eq!(hit.fill, 0.6); // exact the frame it lands
/// assert_eq!(hit.trail, 1.0); // the lost length lingers
/// ```
pub fn meter_motion(
    shown: MeterShown,
    target: f32,
    dt: f32,
    gain: Spring,
    duration_scale: f32,
) -> MeterShown {
    let target = if target.is_finite() {
        target.clamp(0.0, 1.0)
    } else {
        0.0
    };
    if !(duration_scale.is_finite() && duration_scale > 0.0) {
        return MeterShown {
            fill: target,
            trail: target,
            hold: 0.0,
            speed: 0.0,
            aim: target,
        };
    }
    let real_dt = if dt.is_finite() { dt.max(0.0) } else { 0.0 };
    let dt = real_dt / duration_scale;
    let mut next = shown;
    // A trail already standing keeps its own clock: only a loss with none starts one.
    let mut fresh = false;
    let overshoot = shown.speed != 0.0 && shown.aim == target;
    if target < shown.fill && !overshoot {
        next.fill = target;
        next.speed = 0.0;
        next.aim = target;
        if shown.trail <= shown.fill {
            next.trail = shown.fill;
            next.hold = METER_TRAIL_HOLD_SECONDS;
            fresh = true;
        }
    } else if target > shown.fill || shown.speed != 0.0 {
        // The spring is the skin's; the player's scale stretches its length, so `dt` here is the
        // real one.
        let spring = gain.scaled(duration_scale);
        let state = spring_step(
            spring,
            SpringState {
                value: shown.fill,
                velocity: shown.speed,
            },
            target,
            real_dt,
        );
        if spring_settled(spring, state, target, METER_SNAP) {
            next.fill = target;
            next.speed = 0.0;
        } else {
            next.fill = state.value.clamp(0.0, 1.0);
            next.speed = state.velocity;
        }
        next.aim = target;
    }
    next.trail = next.trail.max(next.fill);
    if next.trail > next.fill {
        if !fresh {
            let over = dt - next.hold;
            next.hold = (next.hold - dt).max(0.0);
            if over > 0.0 {
                next.trail = (next.trail - METER_TRAIL_RATE * over).max(next.fill);
            }
        }
        if next.trail - next.fill < METER_SNAP {
            next.trail = next.fill;
        }
    }
    if next.trail <= next.fill {
        next.hold = 0.0;
    }
    next
}

/// The `UiScale` that keeps an interface's share of a `width` × `height` window (logical px): the
/// window's shorter side over `reference_short_side`, times the player's `scale`. `None` when there
/// is no usable scale: a window with no size (minimised), or a reference or a scale that is not
/// above zero.
///
/// ```
/// assert_eq!(bevy_gooey::window_ui_scale(2560.0, 1440.0, 720.0, 1.0), Some(2.0));
/// ```
pub fn window_ui_scale(
    width: f32,
    height: f32,
    reference_short_side: f32,
    scale: f32,
) -> Option<f32> {
    let ui = width.min(height) / reference_short_side * scale;
    (reference_short_side > 0.0 && scale > 0.0 && ui > 0.0 && ui.is_finite()).then_some(ui)
}

/// How close to a whole device pixel a line already is to count as that pixel: a thousandth.
const SNAP_TOLERANCE: f32 = 1.0e-3;

/// A line weight `length` (logical px) snapped so it draws as a whole number of device pixels at
/// `scale` device pixels per logical px: CSS's "snap a length as a border width". Above one device
/// pixel it rounds down, below one it rounds up to one, and zero stays zero. Returns logical px.
///
/// Bevy lays a node out at `scale × length` and rounds each edge from the node's position, so a
/// 4.5 px border draws 4 px on one side and 5 px on another; a whole-pixel border draws the same on
/// every side. The result is chosen so that `scale * result`, as `f32`, is exactly the whole number
/// wherever an `f32` allows it, and otherwise the least length above it, never below.
///
/// A length or scale that is not finite and above zero is returned unchanged.
///
/// ```
/// // 3 px at 1.5x would be 4.5 device px: it is drawn 4.
/// let line = bevy_gooey::snap_line_width(3.0, 1.5);
/// assert_eq!(line * 1.5, 4.0);
/// ```
pub fn snap_line_width(length: f32, scale: f32) -> f32 {
    let usable = |x: f32| x.is_finite() && x > 0.0;
    if !usable(length) || !usable(scale) {
        return length;
    }
    let device = (length * scale + SNAP_TOLERANCE).floor().max(1.0);
    logical_for_device(device, scale)
}

/// A text size `size` (logical px) raised to the smallest one whose device size at `scale` device
/// pixels per logical px is a whole number, so glyphs are drawn at a whole pixel size and the lines
/// they set stay on the pixel grid. Returns logical px, less than one device pixel above `size`.
/// A size within a thousandth of a device pixel above a whole number counts as that number, as for
/// [`snap_line_width`], so a size already on the grid is not pushed a pixel up by rounding noise;
/// that thousandth is the most the result is ever below `size`.
///
/// `scale` is the one Bevy lays the text out at: the window's scale factor times [`bevy::ui::UiScale`]
/// (`ComputedUiRenderTargetInfo::scale_factor`). The result is chosen so that `scale * result`, as
/// `f32`, is the whole number wherever an `f32` allows it, and otherwise the least size above it.
///
/// A size or scale that is not finite and above zero is returned unchanged.
///
/// ```
/// // 15.4 px at 1.25x would be 19.25 device px: it is set at 20.
/// let size = bevy_gooey::snap_text_size(15.4, 1.25);
/// assert_eq!(size * 1.25, 20.0);
/// // 16 px at 1.5x is already 24 device px.
/// assert_eq!(bevy_gooey::snap_text_size(16.0, 1.5), 16.0);
/// ```
pub fn snap_text_size(size: f32, scale: f32) -> f32 {
    let usable = |x: f32| x.is_finite() && x > 0.0;
    if !usable(size) || !usable(scale) {
        return size;
    }
    let device = (size * scale - SNAP_TOLERANCE).ceil().max(1.0);
    logical_for_device(device, scale)
}

/// The logical length whose product with `scale`, as `f32`, is exactly `device`, or failing that
/// the least one above it.
fn logical_for_device(device: f32, scale: f32) -> f32 {
    let mut logical = device / scale;
    // Division and multiplication each round, so step by ulps until the product is exact, or
    // failing that, the least one above: a product an ulp short rounds a pixel short.
    for _ in 0..4 {
        let drawn = logical * scale;
        if drawn < device {
            logical = logical.next_up();
        } else if drawn > device && logical.next_down() * scale >= device {
            logical = logical.next_down();
        } else {
            break;
        }
    }
    logical
}

/// How long a held D-pad direction waits before it repeats on a [`crate::slider`], in seconds. A
/// design default: the delay of a keyboard's own repeat.
pub const PAD_REPEAT_DELAY: f32 = 0.4;

/// How many repeats a second a held D-pad direction makes on a [`crate::slider`], once the delay
/// is over. A design default: with a twentieth of the range a step, a 0 to 1 slider sweeps in about
/// two seconds.
pub const PAD_REPEAT_RATE: f32 = 12.0;

/// How far a stick must be pushed, as a share of its travel (after the pad's own dead zone), to
/// count as the player using a pad: [`crate::track_input_device`] switches
/// [`crate::InputDevice`] to the pad on a push this far. Half its travel is a deliberate push, and
/// leaves a drifting or brushed stick alone. A design default.
pub const STICK_PUSH: f32 = 0.5;

/// How far a stick must be pushed, as a share of its travel, to point a [`crate::radial`] at an
/// item: half, a deliberate push. Inside it the highlight stays where it is, so a stick drifting
/// through the middle on its way back never flickers between items. A design default, the same
/// half as [`STICK_PUSH`].
pub const RADIAL_STICK_PUSH: f32 = 0.5;

/// How far from the middle of a [`crate::radial`] the pointer must be to point at an item, as a
/// share of the disc's radius. Inside it the highlight stays, which is the dead zone a pointer
/// needs for the same reason a stick does. A design default.
pub const RADIAL_DEAD_ZONE: f32 = 0.25;

/// The item of `count` on a ring that the direction `(x, y)` points into, with `y` up: item 0 is at
/// the top and the rest follow clockwise, each owning the wedge of `360 / count` degrees centred on
/// it. The edge between two wedges belongs to the clockwise one. A direction of no length, or a
/// non-finite one, and a ring of one, pick item 0; a ring of none picks nothing, so `None`.
///
/// ```
/// use bevy_gooey::radial_pick;
/// assert_eq!(radial_pick(0.0, 1.0, 4), Some(0)); // up
/// assert_eq!(radial_pick(1.0, 0.0, 4), Some(1)); // right
/// assert_eq!(radial_pick(0.0, -1.0, 4), Some(2)); // down
/// assert_eq!(radial_pick(-1.0, 0.0, 4), Some(3)); // left
/// assert_eq!(radial_pick(1.0, 1.0, 8), Some(1)); // up and right
/// assert_eq!(radial_pick(1.0, 1.0, 0), None);
/// ```
pub fn radial_pick(x: f32, y: f32, count: usize) -> Option<usize> {
    if count == 0 {
        return None;
    }
    if !(x.is_finite() && y.is_finite()) || (x == 0.0 && y == 0.0) {
        return Some(0);
    }
    let turns = (x.atan2(y) / std::f32::consts::TAU).rem_euclid(1.0);
    // The half-wedge nudge puts a wedge's edge in the clockwise item; the epsilon keeps an angle
    // that float error leaves a hair short of the edge (a diagonal of an even ring) on that side.
    Some(((turns * count as f32 + 0.5 + 1e-4).floor() as usize) % count)
}

/// Where item `index` of `count` stands on a ring, as the offset from the middle in half-widths of
/// the disc: `(x, y)` with `y` up, on a circle of radius 1. Item 0 is at the top, the rest clockwise
/// (the same order as [`radial_pick`]). An `index` past the ring wraps.
///
/// ```
/// let (x, y) = bevy_gooey::radial_place(1, 4);
/// assert!((x - 1.0).abs() < 1e-6 && y.abs() < 1e-6); // the right
/// ```
pub fn radial_place(index: usize, count: usize) -> (f32, f32) {
    if count == 0 {
        return (0.0, 1.0);
    }
    let angle = (index % count) as f32 / count as f32 * std::f32::consts::TAU;
    (angle.sin(), angle.cos())
}

/// The item a step of `delta` from `value` reaches on a ring of `count`: wrapping round both ways,
/// as a ring has no end. A `value` past the ring counts as the last item. Zero for a ring of none.
///
/// ```
/// use bevy_gooey::radial_step;
/// assert_eq!(radial_step(3, 4, 1), 0);
/// assert_eq!(radial_step(0, 4, -1), 3);
/// assert_eq!(radial_step(1, 8, 10), 3);
/// ```
pub fn radial_step(value: usize, count: usize, delta: i32) -> usize {
    if count == 0 {
        return 0;
    }
    let at = value.min(count - 1) as i64;
    (at + i64::from(delta)).rem_euclid(count as i64) as usize
}

/// The slot Home or End moves a grid's cursor to, in a grid `columns` wide holding `len` slots in
/// reading order: the first or last slot of `index`'s row (the last row may be short), or with
/// `whole` the first or last slot of the grid. Never past the last slot, and `0` for an empty
/// grid.
///
/// ```
/// use bevy_gooey::slot_edge;
/// // Seven slots, three wide: rows 0-2, 3-5, 6.
/// assert_eq!(slot_edge(4, 3, 7, false, false), 3);
/// assert_eq!(slot_edge(4, 3, 7, true, false), 5);
/// assert_eq!(slot_edge(6, 3, 7, true, false), 6);
/// assert_eq!(slot_edge(4, 3, 7, true, true), 6);
/// ```
pub fn slot_edge(index: usize, columns: usize, len: usize, end: bool, whole: bool) -> usize {
    let Some(last) = len.checked_sub(1) else {
        return 0;
    };
    let columns = columns.max(1);
    match (end, whole) {
        (false, true) => 0,
        (true, true) => last,
        (false, false) => index.min(last) / columns * columns,
        (true, false) => (index.min(last) / columns * columns + columns - 1).min(last),
    }
}

/// How far along its range a slider's thumb is, from 0 to 1. Never NaN: a value outside the range
/// is clamped to an end, and a range that is not finite or has no length reads as the start.
///
/// ```
/// assert_eq!(bevy_gooey::slider_fraction(25.0, 0.0, 100.0), 0.25);
/// assert_eq!(bevy_gooey::slider_fraction(2.0, 0.0, 1.0), 1.0);
/// ```
pub fn slider_fraction(value: f32, min: f32, max: f32) -> f32 {
    if min.is_finite() && max.is_finite() && value.is_finite() && max > min {
        ((value - min) / (max - min)).clamp(0.0, 1.0)
    } else {
        0.0
    }
}

/// The text a [`crate::slider`] shows for its value: a percentage when the range is 0 to 1 (a
/// volume, a brightness), the plain number otherwise, rounded to two decimals with trailing zeros
/// dropped. A value outside the range reads as the end it is clamped to, and one that is not finite
/// as 0.
///
/// ```
/// assert_eq!(bevy_gooey::slider_text(0.7, 0.0, 1.0), "70%");
/// assert_eq!(bevy_gooey::slider_text(1.25, 0.5, 2.0), "1.25");
/// assert_eq!(bevy_gooey::slider_text(40.0, 0.0, 100.0), "40");
/// ```
pub fn slider_text(value: f32, min: f32, max: f32) -> String {
    let value = if value.is_finite() { value } else { 0.0 };
    let value = if min.is_finite() && max.is_finite() && min <= max {
        value.clamp(min, max)
    } else {
        value
    };
    if min == 0.0 && max == 1.0 {
        return format!("{}%", (value * 100.0).round());
    }
    let text = format!("{value:.2}");
    let text = text.trim_end_matches('0').trim_end_matches('.');
    // A value that rounds to nothing is "0", never "-0".
    if text == "-0" || text.is_empty() {
        "0".into()
    } else {
        text.into()
    }
}

/// Where a [`crate::choice`] lands when it steps `delta` options from `selected` among `len`:
/// clamped to the first and the last, never wrapping, so a player who steps past the end sees that
/// it is the end. With no options it stays at 0, and a `selected` already past the end counts as
/// the last.
///
/// ```
/// assert_eq!(bevy_gooey::choice_step(1, 3, 1), 2);
/// assert_eq!(bevy_gooey::choice_step(2, 3, 1), 2);
/// assert_eq!(bevy_gooey::choice_step(0, 3, -1), 0);
/// ```
pub fn choice_step(selected: usize, len: usize, delta: i32) -> usize {
    let last = len.saturating_sub(1);
    let from = selected.min(last);
    if delta < 0 {
        from.saturating_sub(delta.unsigned_abs() as usize)
    } else {
        from.saturating_add(delta as usize).min(last)
    }
}

/// The option after `selected` among `len`, wrapping from the last to the first: what Enter, Space,
/// the pad's South button and a click on a [`crate::choice`]'s value do, so one repeated press
/// reaches every option. With no options it stays at 0.
///
/// ```
/// assert_eq!(bevy_gooey::choice_next(0, 3), 1);
/// assert_eq!(bevy_gooey::choice_next(2, 3), 0);
/// ```
pub fn choice_next(selected: usize, len: usize) -> usize {
    if len == 0 {
        0
    } else {
        (selected.min(len - 1) + 1) % len
    }
}

